"""The check index, `plugin/checks/INDEX.md`, generated from check headers
(docs/decisions/D-DBA-7-generated-check-index.md).

The output depends only on the headers and each file's `<category>/<name>`, so it
is byte-identical wherever the tree lives: LF line endings, no timestamps.
The merged user index (`build_merged_index`) holds absolute paths, so it is not.
"""

from itertools import groupby
from pathlib import Path

from tools.checks.header import Check, CheckFormatError, parse_check

COLUMNS = ("id", "title", "mode", "pack", "min_version", "file")

PREAMBLE = """\
# Check index

Generated by `python -m tools index` from the check file headers. Do not edit by hand:
after adding or changing a check, rerun the command. `file` is relative to `plugin/checks/`.
"""

MERGED_COLUMNS = COLUMNS + ("source",)

MERGED_PREAMBLE = """\
# Check index (built-in and user checks)

Generated by `python -m tools index --user` from the built-in checks and the user checks
in this folder. Do not edit by hand: after adding or changing a user check, rerun the
command. A user check with a built-in id replaces it. `file` is an absolute path.
"""


def load_check(path) -> Check:
    """`parse_check(path)`, with the path in the message of a `CheckFormatError`."""
    try:
        return parse_check(path)
    except CheckFormatError as exc:
        raise CheckFormatError(exc.code, exc.line, f"{path}: {exc.message}") from exc


def discover(root) -> list[Check]:
    """A `Check` for every `.sql` file under `root`, in path order."""
    return [load_check(path) for path in sorted(Path(root).rglob("*.sql"))]


def find_check(root, check_id: str) -> Check | None:
    """The check under `root` whose id is `check_id`, or None. Lint L003 ties the id
    to the file name, so only `<id>.sql` files are parsed."""
    candidates = (parse_check(p) for p in sorted(Path(root).rglob(f"{check_id}.sql")))
    return next((c for c in candidates if c.id == check_id), None)


def _row(cells) -> str:
    return "| " + " | ".join(str(c).replace("|", "\\|") for c in cells) + " |"


def _cells(c: Check, file: str) -> tuple:
    return (c.id, c.title, c.mode, c.pack, c.min_version, file)


def _render(preamble: str, columns, rows) -> str:
    """The preamble, then one table per category sorted by id; `rows` are
    (category, cells) with the id first in cells."""
    parts = [preamble]
    for category, group in groupby(sorted(rows), key=lambda r: r[0]):
        lines = [f"## {category}", "", _row(columns), _row("---" for _ in columns)]
        lines += [_row(cells) for _, cells in group]
        parts.append("\n".join(lines) + "\n")
    return "\n".join(parts)


def build_index(checks) -> str:
    """INDEX.md text for `plugin/checks/`, with `file` relative to it."""
    return _render(PREAMBLE, COLUMNS, [
        (c.category, _cells(c, f"{c.path.parent.name}/{c.path.name}")) for c in checks
    ])


def build_merged_index(resolved) -> str:
    """`<pack_home>/checks/INDEX.md` text from `ResolvedCheck`s: an extra `source`
    column, and `file` as an absolute path since checks come from two roots."""
    return _render(MERGED_PREAMBLE, MERGED_COLUMNS, [
        (r.check.category, _cells(r.check, str(r.check.path.resolve())) + (r.source,))
        for r in resolved
    ])
