def test_both_extractors_render_through_the_shared_module():
    """AC: the capped-table and Markdown code lives once, in tools/offline/render.py;
    extract-awr and extract-ash import it and define no rendering of their own.
    A source scan: which module a command delegates to has no behavioural seam."""
    for module in ("extract_awr", "extract_ash"):
        tree = ast.parse((COMMANDS_DIR / f"{module}.py").read_text(encoding="utf-8"))
        imports = {
            node.module for node in ast.walk(tree) if isinstance(node, ast.ImportFrom)
        } | {a.name for node in ast.walk(tree) if isinstance(node, ast.Import) for a in node.names}
        assert "tools.offline.render" in imports, f"{module} does not import tools.offline.render"
        defined = [n.name for n in ast.walk(tree) if isinstance(n, ast.FunctionDef)]
        own = [n for n in defined if re.search(r"capped|md_cell|markdown", n)]
        assert not own, f"{module} defines its own rendering: {own}"


