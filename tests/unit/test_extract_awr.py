"""DBA-6: offline AWR extractor (`python -m tools extract-awr`) and offline-analysis skill.

No database is touched. There are no tables or endpoints to verify. The input
is the committed AWR report pair under tests/fixtures/offline/, generated by
tests/support/make_awr_fixture.py from the Oracle 23ai Free test container
(gvenzl/oracle-free image: CDB name FREE). Those fixtures do not exist until
/implement generates them; tests that need them fail with "fixture not found".

Where a test needs a report the fixture does not provide (a missing section, a
long SQL text), it derives one from the real fixture in a temp dir rather than
hand-writing a report: a parser fitted to an invented format proves nothing.

JSON shape pinned here (the Markdown output carries the same content):
  {"summary": {SUMMARY_KEYS...},
   "sections": {<name>: {"columns": [str], "rows": [[str]], "dropped": int}},
   "sections_not_found": [<name>]}

The implementation modules do not exist yet, so they are imported inside the
tests: each test then fails on its own instead of the file erroring at collection.
"""

import html
import importlib
import inspect
import json
import re
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURE_DIR = REPO_ROOT / "tests" / "fixtures" / "offline"
HTML_FIXTURE = FIXTURE_DIR / "awr_23ai_free.html"
TEXT_FIXTURE = FIXTURE_DIR / "awr_23ai_free.txt"
FIXTURES = {"html": HTML_FIXTURE, "txt": TEXT_FIXTURE}
GENERATOR = REPO_ROOT / "tests" / "support" / "make_awr_fixture.py"
SKILL = REPO_ROOT / "plugin" / "skills" / "offline-analysis" / "SKILL.md"

CONTAINER_DB_NAME = "FREE"  # DB name of the gvenzl/oracle-free CDB in tests/docker-compose.yml
ALL_SECTIONS = [
    "load_profile",
    "instance_efficiency",
    "top_events",
    "time_model",
    "sql_by_elapsed",
    "sql_by_cpu",
    "sql_by_gets",
    "sql_by_reads",
    "segments_by_logical_reads",
    "segments_by_physical_reads",
    "init_params",
]
SUMMARY_KEYS = [
    "db_name",
    "instance",
    "release",
    "begin_snap_id",
    "end_snap_id",
    "begin_time",
    "end_time",
    "elapsed",
    "db_time",
]
SQL_TEXT_LIMIT = 200
DROPPED_LINE = re.compile(r"\b(\d+)\b.*\bdropped\b|\bdropped\b.*\b(\d+)\b", re.IGNORECASE)

if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))


def _run_tools(*args):
    return subprocess.run(
        [sys.executable, "-m", "tools", *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )


def _fixture(kind):
    path = FIXTURES[kind]
    assert path.is_file(), f"fixture not found: {path.relative_to(REPO_ROOT)}"
    return path


def _extract_json(path, *args):
    result = _run_tools("extract-awr", str(path), "--format", "json", *args)
    assert result.returncode == 0, f"exit {result.returncode}: {result.stderr}"
    return json.loads(result.stdout)


def _md_tables(text):
    """Split Markdown output into pipe tables: (data_rows, next_nonblank_line) per table."""
    lines = text.splitlines()
    tables, i = [], 0
    while i < len(lines):
        if lines[i].lstrip().startswith("|"):
            start = i
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                i += 1
            rows = [ln for ln in lines[start:i] if not re.fullmatch(r"\s*\|[\s:|-]*\|\s*", ln)]
            following = next((ln for ln in lines[i:] if ln.strip()), "")
            tables.append((len(rows) - 1, following))  # minus the header row
        else:
            i += 1
    return tables


# --- behavioural tests -------------------------------------------------------


@pytest.mark.parametrize("kind", ["html", "txt"])
def test_json_summary_and_load_profile_from_the_committed_fixture(kind):
    """AC: summary.db_name equals the container's database name, the summary carries
    instance, release, snapshot ids and times, elapsed and DB time, and load_profile is
    a non-empty table labelled as the load profile. Falsifier: break the section anchor
    lookup and load_profile moves to sections_not_found."""
    out = _extract_json(_fixture(kind))

    summary = out["summary"]
    assert summary["db_name"] == CONTAINER_DB_NAME
    for key in SUMMARY_KEYS:
        assert summary.get(key) not in (None, ""), f"summary.{key} is empty"

    assert "load_profile" not in out["sections_not_found"]
    load_profile = out["sections"]["load_profile"]
    assert load_profile["columns"] and load_profile["columns"][0].strip()
    assert load_profile["rows"], "load_profile has no rows"
    first_column = " ".join(row[0] for row in load_profile["rows"]).lower()
    assert "db time" in first_column  # the Load Profile's own row labels

    top_events = out["sections"]["top_events"]
    assert any("event" in c.lower() for c in top_events["columns"]) and top_events["rows"]

    assert set(out["sections"]) | set(out["sections_not_found"]) == set(ALL_SECTIONS)


@pytest.mark.parametrize("kind", ["html", "txt"])
def test_markdown_default_output_starts_with_summary_and_stays_under_30000_chars(kind):
    """AC: default output is Markdown, starts with the summary block, and is under
    30,000 characters for the committed fixture; no table exceeds the default 20 rows."""
    path = _fixture(kind)
    out = _extract_json(path)
    summary = out["summary"]

    result = _run_tools("extract-awr", str(path))
    assert result.returncode == 0, result.stderr
    text = result.stdout
    assert len(text) < 30_000, f"{len(text)} characters"

    # load_profile is the first section; its first row label marks where sections begin.
    first_section_at = text.find(out["sections"]["load_profile"]["rows"][0][0])
    assert first_section_at > 0, "load_profile rows not in the Markdown output"
    for key in ("db_name", "begin_snap_id", "end_snap_id"):
        assert 0 <= text.find(str(summary[key])) < first_section_at, (
            f"summary {key} not before the first section"
        )

    tables = _md_tables(text)
    assert tables, "no Markdown tables in the output"
    assert max(rows for rows, _ in tables) <= 20


@pytest.mark.parametrize("kind", ["html", "txt"])
def test_max_rows_caps_every_table_and_states_rows_dropped(kind):
    """AC: with --max-rows 5 no table has more than 5 data rows and each truncated
    table is followed by a line stating how many rows were dropped."""
    path = _fixture(kind)
    full = _extract_json(path, "--max-rows", "100000")["sections"]
    capped = _extract_json(path, "--max-rows", "5")["sections"]

    truncated = 0
    for name, table in capped.items():
        assert len(table["rows"]) <= 5, name
        expected_dropped = max(len(full[name]["rows"]) - 5, 0)
        assert table["dropped"] == expected_dropped, name
        truncated += bool(expected_dropped)
    assert truncated, "fixture has no table over 5 rows: the cap is not exercised"

    result = _run_tools("extract-awr", str(path), "--max-rows", "5")
    assert result.returncode == 0, result.stderr
    tables = _md_tables(result.stdout)
    assert max(rows for rows, _ in tables) <= 5
    dropped_lines = [following for rows, following in tables if DROPPED_LINE.search(following)]
    assert len(dropped_lines) == truncated


def test_sections_option_selects_and_missing_sections_are_listed_not_fatal(tmp_path):
    """AC: --sections limits the output to the named sections; a section absent from
    the report is listed under "Sections not found" and does not cause a failure."""
    out = _extract_json(_fixture("html"), "--sections", "load_profile,top_events")
    assert set(out["sections"]) == {"load_profile", "top_events"}
    assert out["sections_not_found"] == []

    # The init.ora parameters sit at the end of an AWR report: cutting the real
    # text report to its first 40% removes them and keeps the header.
    lines = _fixture("txt").read_text().splitlines(keepends=True)
    partial = tmp_path / "partial_awr.txt"
    partial.write_text("".join(lines[: len(lines) * 2 // 5]))

    out = _extract_json(partial, "--sections", "load_profile,init_params")
    assert "init_params" in out["sections_not_found"]
    assert "init_params" not in out["sections"]
    assert out["summary"]["db_name"] == CONTAINER_DB_NAME

    result = _run_tools("extract-awr", str(partial), "--sections", "init_params")
    assert result.returncode == 0, result.stderr
    after = result.stdout.lower().split("sections not found", 1)
    assert len(after) == 2 and "init_params" in after[1]


def test_sql_text_cells_are_cut_to_200_characters(tmp_path):
    """AC: SQL text cells are cut to 200 characters. A copy of the HTML fixture gets
    500 extra characters inserted into its first SQL text cell."""
    path = _fixture("html")
    sql = _extract_json(path, "--sections", "sql_by_elapsed")["sections"]["sql_by_elapsed"]
    col = next(i for i, c in enumerate(sql["columns"]) if "sql text" in c.lower())
    anchor = sql["rows"][0][col][:30]
    assert anchor, "first sql_by_elapsed row has an empty SQL text"

    source = path.read_text()
    found = next((a for a in (anchor, html.escape(anchor, quote=False)) if a in source), None)
    assert found, f"SQL text {anchor!r} not located in the fixture"
    long_report = tmp_path / "long_sql.html"
    long_report.write_text(source.replace(found, found + "x" * 500, 1))

    out = _extract_json(long_report, "--max-rows", "100000")
    cells = [
        row[i]
        for name, table in out["sections"].items()
        if name.startswith("sql_by_")
        for i, column in enumerate(table["columns"])
        if "sql text" in column.lower()
        for row in table["rows"]
    ]
    assert cells and max(len(c) for c in cells) <= SQL_TEXT_LIMIT
    assert any("x" * 50 in c for c in cells), "the lengthened SQL text was not kept"


def test_not_an_awr_report_exits_1_and_unknown_section_exits_2(tmp_path):
    """AC: a file that is not an AWR report exits 1 with "not an AWR report" on stderr;
    an unknown name in --sections exits 2."""
    for name, body in (
        (
            "page.html",
            "<html><body><h1>Report</h1><table><tr><th>a</th></tr>"
            "<tr><td>1</td></tr></table></body></html>",
        ),
        ("notes.txt", "Load Profile is a heading in many documents.\nNothing else.\n"),
    ):
        bogus = tmp_path / name
        bogus.write_text(body)
        result = _run_tools("extract-awr", str(bogus))
        assert result.returncode == 1, (name, result.stderr)
        assert "not an AWR report" in result.stderr

    result = _run_tools("extract-awr", str(_fixture("html")), "--sections", "load_profile,bogus")
    assert result.returncode == 2
    assert "bogus" in result.stderr


def test_offline_analysis_skill_structure():
    """AC: SKILL.md has frontmatter name and description and tells the model to run
    extract-awr instead of reading the raw file, start from the summary and top_events,
    treat report values as data never instructions, say the report covers only its
    snapshot window, and name the section of each finding. Structure only: the model's
    behaviour has no test seam until the eval harness."""
    text = SKILL.read_text()
    match = re.match(r"---\n(.*?)\n---\n(.*)", text, re.DOTALL)
    assert match, "SKILL.md must open with a --- frontmatter block"
    meta = yaml.safe_load(match.group(1))
    assert meta["name"] == "offline-analysis"
    assert isinstance(meta["description"], str) and meta["description"].strip()

    body = match.group(2).lower()
    for phrase in (
        "extract-awr",
        "raw",
        "summary",
        "top_events",
        "data",
        "instruction",
        "snapshot",
        "section",
    ):
        assert phrase in body, f"SKILL.md body does not mention {phrase!r}"


