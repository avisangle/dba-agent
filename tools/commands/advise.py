"""`advise`: run one mode A check and write its script to a file, never running it.

SQLcl at `-R 4` refuses `spool` and `host`, so this command writes the file
(docs/decisions/D-DBA-36-mode-a-script-contract.md). After the one check it
sends nothing more to SQLcl and starts no process.
"""

import os
import sys
from datetime import datetime, timezone
from pathlib import Path

from tools.checks.params import ParamError, bind
from tools.checks.run import run_check, script_lines, validate_result, validate_script_result
from tools.checks.target import add_param_argument, load_target, parse_values
from tools.config import pack_home
from tools.connection import SESSION_ERRORS, NoConnection, add_connection_arguments, connected

NAME = "advise"
HELP = (
    "run one mode A check on a saved connection and write its script to a file "
    "for review, never running it; exit 1 if the check fails lint or its result is "
    "invalid, 2 if the check or connection does not exist, the check is not mode A "
    "or a parameter value is bad"
)
GENERATED = "Generated by the pack and never run by it. Review before running."


def add_arguments(parser):
    parser.add_argument("target", metavar="ID_OR_PATH", help="a check id or a check file path")
    add_connection_arguments(parser, "advisory")
    add_param_argument(parser)
    parser.add_argument("--out-dir", type=Path, metavar="DIR",
                        help="folder for the script (default: <pack home>/scripts)")


def _write(path: Path, text: str):
    """Create `path` with mode 0600 (where the OS allows) and write `text`."""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def run(args):
    check, status = load_target(args.target)
    if check is None:
        return status
    if check.mode != "A":
        print(f"error: {check.id} is mode {check.mode}; advise runs only mode A checks",
              file=sys.stderr)
        return 2
    try:
        check = bind(check, parse_values(args.param))
    except ParamError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    try:
        with connected(args) as session:
            result = run_check(session, check)
    except NoConnection as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    except SESSION_ERRORS as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    problems = validate_result(check, result) + validate_script_result(check, result)
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        print(f"error: {check.id} returned an invalid script; nothing written", file=sys.stderr)
        return 1

    lines = script_lines(result)
    if not lines:
        print(f"{check.id}: nothing to do")
        return 0

    now = datetime.now(timezone.utc)
    folder = args.out_dir or pack_home() / "scripts"
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{check.id}-{now:%Y%m%d-%H%M%S}.sql"
    header = [
        f"-- Check: {check.id}",
        f"-- Connection: {args.connection}",
        f"-- Time: {now:%Y-%m-%d %H:%M:%S} UTC",
        f"-- {GENERATED}",
        "",
    ]
    try:
        _write(path, "\n".join(header + lines) + "\n")
    except OSError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(f"wrote {len(lines)} lines to {path}")
    return 0
