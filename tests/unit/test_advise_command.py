def test_validate_script_result_accepts_increasing_integer_line_numbers():
    """AC: validate_script_result(check, result) is empty for a result with
    LINE_NO and SCRIPT_LINE whose LINE_NO values are integers in strictly
    increasing order (gaps allowed, compared as numbers: 9 before 10), with
    facts columns in any order, and for a zero-row result with both columns."""
    validate = _validate_script_result()
    check = parse_check(MODE_A_CHECK)

    assert validate(check, _script_result()) == []
    facts = _result(["SCRIPT_LINE", "OWNER", "LINE_NO", "SEVERITY"],
                    [[line, "APP", n, "INFO"] for n, line in SCRIPT])
    assert validate(check, facts) == []
    assert validate(check, _result(["LINE_NO", "SCRIPT_LINE", "SEVERITY"], [])) == []


@pytest.mark.parametrize("label, header, rows", [
    ("no LINE_NO", ["SCRIPT_LINE", "SEVERITY"], [["x;", "INFO"]]),
    ("no SCRIPT_LINE", ["LINE_NO", "SEVERITY"], [[1, "INFO"]]),
    ("not an integer", ["LINE_NO", "SCRIPT_LINE", "SEVERITY"],
     [[1, "a;", "INFO"], ["2.5", "b;", "INFO"]]),
    ("empty LINE_NO", ["LINE_NO", "SCRIPT_LINE", "SEVERITY"], [["", "a;", "INFO"]]),
    ("repeated", ["LINE_NO", "SCRIPT_LINE", "SEVERITY"], [[1, "a;", "INFO"], [1, "b;", "INFO"]]),
    ("decreasing", ["LINE_NO", "SCRIPT_LINE", "SEVERITY"],
     [[10, "a;", "INFO"], [9, "b;", "INFO"]]),
])
def test_validate_script_result_reports_a_broken_script_contract(label, header, rows):
    """AC: a problem (non-empty list of strings) when LINE_NO or SCRIPT_LINE is
    missing, a LINE_NO is not an integer, or LINE_NO is not strictly
    increasing. validate_result is unchanged: it passes these results."""
    from tools.checks.run import validate_result

    check = parse_check(MODE_A_CHECK)
    result = _result(header, rows)
    problems = _validate_script_result()(check, result)
    assert problems and all(isinstance(p, str) for p in problems), (label, problems)
    assert validate_result(check, result) == [], label


def test_advise_writes_script_lines_in_line_no_order(tmp_path):
    """AC: `advise <ID> --connection NAME` runs the check once, writes
    `<pack_home>/scripts/<id>-<YYYYmmdd-HHMMSS>.sql` with mode 0600, a comment
    header (check id, connection, UTC time, GENERATED) and then the SCRIPT_LINE
    values in LINE_NO order, and prints the path and line count. Falsifier:
    sort by SCRIPT_LINE (or LINE_NO as text) and the body differs."""
    exe, log = _fake_sqlcl(tmp_path / "fake", _script_result().text)

    proc = _advise(tmp_path, str(MODE_A_CHECK), "--connection", CONNECTION, sqlcl=exe)
    _command_exists(proc)
    assert proc.returncode == 0, (proc.stdout, proc.stderr)

    written = _written(tmp_path)
    assert len(written) == 1, written
    path = written[0]
    match = FILE_NAME.match(path.name)
    assert match and match["id"] == "mode_a_script", path.name
    datetime.strptime(match["stamp"], "%Y%m%d-%H%M%S")
    if os.name != "nt":
        assert stat.S_IMODE(path.stat().st_mode) == 0o600, oct(path.stat().st_mode)

    header, body = _split(path, len(SCRIPT))
    assert body == [line for _, line in SCRIPT]
    assert header and all(not ln.strip() or ln.startswith("--") for ln in header), header
    head = "\n".join(header)
    for expected in ("mode_a_script", CONNECTION, "UTC", GENERATED):
        assert expected in head, (expected, head)

    assert str(path) in proc.stdout, proc.stdout
    assert re.search(rf"\b{len(SCRIPT)}\b", proc.stdout.replace(str(path), "")), proc.stdout


def test_advise_out_dir_default_tier_home_and_a_single_sqlcl_query(tmp_path):
    """AC: `--out-dir DIR` writes there and not under the pack home; without
    `--home` SQLcl starts on the advisory tier's home
    (`<pack_home>/homes/advisory`); the check's SQL is sent once, unchanged, and
    no other SQL or SQLcl command is sent. `--tier advisory` is accepted."""
    exe, log = _fake_sqlcl(tmp_path / "fake", _script_result().text)
    out_dir = tmp_path / "out"
    out_dir.mkdir()

    proc = _advise(tmp_path, str(MODE_A_CHECK), "--connection", CONNECTION,
                   "--tier", "advisory", "--out-dir", str(out_dir), sqlcl=exe)
    _command_exists(proc)
    assert proc.returncode == 0, (proc.stdout, proc.stderr)
    assert _written(tmp_path) == []
    files = _files(out_dir)
    assert len(files) == 1 and FILE_NAME.match(files[0].name), files
    assert _split(files[0], len(SCRIPT))[1] == [line for _, line in SCRIPT]

    argv, calls = _log(log)
    assert str(tmp_path / "pack-home" / "homes" / "advisory") in argv, argv
    queries = [c for c in calls if c["name"] in ("run-sql", "sql_run")]
    assert [c["arguments"]["sql"] for c in queries] == [parse_check(MODE_A_CHECK).sql]
    assert not [c for c in calls if c["name"] in ("run-sqlcl", "sqlcl_run")], calls


