"""DBA-29: offline AWR report comparison (`python -m tools compare-awr FIRST SECOND`).

No database is touched. The inputs are committed AWR reports from the Oracle 23ai
Free test container, made by tests/support/make_awr_fixture.py:
  awr_23ai_free.{html,txt}    the existing pair (DBA-6); must not change
  awr_23ai_free_b.{html,txt}  a second pair from a different workload window,
                              generated by /implement with `--stem awr_23ai_free_b`
Until the second pair exists, tests that need it fail with "fixture not found".

Expected values are never typed in: they are read from the two files through the
existing parser `tools.offline.awr.parse_awr`, so the tests hold for whatever
workload the second pair records. Source columns used (as parse_awr names them):
  load_profile    [<row label>, "Per Second", ...]
  top_events      ["Event", "Waits", "Total Wait Time (sec)", ..., "% DB time", ...]
  sql_by_elapsed  ["Elapsed Time (s)", "Executions", ..., "SQL Id", ..., "SQL Text"]

JSON shape pinned here (Markdown carries the same rows):
  {"summary": {"first":  {SUMMARY_KEYS..., "db_time_per_second": str},
               "second": {...same keys}},
   "notes": [str],   # e.g. different databases or releases; [] when neither differs
   "sections": {"load_profile" | "top_events" | "sql_by_elapsed":
                {"columns": [str], "rows": [[str]], "dropped": int}}}
Cells are strings. Report figures are copied verbatim; computed cells
(Difference, % change, db_time_per_second) are plain numbers, commas allowed;
a cell with no value is "".
"""

