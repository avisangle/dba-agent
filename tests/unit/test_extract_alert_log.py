def test_planted_ora_codes_are_counted_once_per_record():
    """AC: ora_errors has one row per ORA- code with its count, first and last time
    and first message line, most frequent first; tests assert the planted codes and
    counts from the fixture. Falsifier: count the same record twice (ORA-20282 sits
    on two lines of one record, ORA-06512 four times in the DBMS_QOPATCH record)
    and the planted-count assertion fails."""
    records = _raw()
    raw_counts = _raw_ora_counts(records)
    for code, n in PLANTED.items():
        planted = _holding(records, code)
        assert len(planted) == n, f"fixture: {code} must be in {n} records, is in {len(planted)}"
        assert all(any(PLANT_TAG in ln for ln in lines) for _, lines in planted), code
    lines_20282 = [ln for _, lines in _holding(records, "ORA-20282") for ln in lines]
    assert sum("ORA-20282" in ln for ln in lines_20282) >= 2, "fixture: ORA-20282 on one line only"

    rows = _table(_extract_json(_fixture(), *ALL_ROWS), "ora_errors")
    by_code = {row["code"]: row for row in rows}
    assert {code: int(by_code[code]["count"]) for code in PLANTED if code in by_code} == PLANTED
    assert {code: int(row["count"]) for code, row in by_code.items()} == raw_counts

    counts = [int(row["count"]) for row in rows]
    assert counts == sorted(counts, reverse=True), "ora_errors is not most frequent first"
    for code, row in by_code.items():
        holding = _holding(records, code)
        assert row["first_time"] == holding[0][0], code
        assert row["last_time"] == holding[-1][0], code
        assert code in row["message"] and len(row["message"]) <= TEXT_LIMIT, (code, row["message"])
    first_planted = next(ln for ln in _holding(records, "ORA-20281")[0][1] if "ORA-20281" in ln)
    assert PLANT_TAG in by_code["ORA-20281"]["message"]
    assert by_code["ORA-20281"]["message"] in first_planted


def test_summary_counts_records_by_timestamp_line_and_log_switches(tmp_path):
    """AC: the summary gives first and last record time and the record count; a
    record starts at a line that is only an ISO 8601 timestamp, and lines before the
    first one (a fresh container's log, a log cut mid-record) are not a record and
    not fatal. Log switch and "Checkpoint not complete" counts equal the lines in
    the raw log."""
    records = _raw()
    switches = _lines_matching(records, LOG_SWITCH_LINE)
    checkpoints = _lines_matching(records, CHECKPOINT_LINE)
    assert switches, "fixture: no log switch"
    assert checkpoints, "fixture: no Checkpoint not complete"

    summary = _extract_json(_fixture())["summary"]
    assert set(summary) == SUMMARY_KEYS, sorted(summary)
    assert summary["first_time"] == records[0][0]
    assert summary["last_time"] == records[-1][0]
    assert int(summary["records"]) == len(records)
    assert summary["since"] is None
    assert int(summary["window_records"]) == len(records)
    assert int(summary["log_switches"]) == len(switches)
    assert int(summary["checkpoint_not_complete"]) == len(checkpoints)

    # The same log with its first timestamp line removed starts with untimed lines.
    lines = _fixture().read_text(encoding="utf-8").splitlines(keepends=True)
    first = next(i for i, ln in enumerate(lines) if TIMESTAMP_LINE.fullmatch(ln.rstrip("\n")))
    cut = tmp_path / "alert_cut.log"
    cut.write_text("".join(lines[:first] + lines[first + 1 :]), encoding="utf-8")
    summary = _extract_json(cut)["summary"]
    assert int(summary["records"]) == len(records) - 1
    assert summary["first_time"] == records[1][0]


def test_since_limits_every_table_and_the_window_count():
    """AC: --since YYYY-MM-DD[THH:MM] sets the window: the summary keeps the whole
    file's first and last time and record count, and reports the window; ora_errors,
    events and recent_errors cover only records at or after it. Falsifier: drop the
    --since filter and the windowed planted count fails."""
    records = _raw()
    since = _since(records)
    window = [(t, lines) for t, lines in records if t[:16] >= since]
    expected = len(_holding(window, "ORA-20281"))
    assert 0 < expected < PLANTED["ORA-20281"], (since, expected)

    out = _extract_json(_fixture(), "--since", since, *ALL_ROWS)
    summary = out["summary"]
    assert summary["since"] == since
    assert int(summary["records"]) == len(records)
    assert summary["first_time"] == records[0][0]
    assert int(summary["window_records"]) == len(window)
    assert int(summary["log_switches"]) == len(_lines_matching(window, LOG_SWITCH_LINE))

    by_code = {row["code"]: row for row in _table(out, "ora_errors")}
    assert int(by_code["ORA-20281"]["count"]) == expected
    assert {c: int(r["count"]) for c, r in by_code.items()} == _raw_ora_counts(window)
    assert all(r["time"][:16] >= since for r in _table(out, "events")), "events before --since"
    assert all(r["time"][:16] >= since for r in _table(out, "recent_errors"))

    # The date-only form; a date before the log keeps every record.
    out = _extract_json(_fixture(), "--since", "2000-01-01")
    assert int(out["summary"]["window_records"]) == len(records)


def test_events_list_starts_shutdowns_and_alter_commands_with_their_time():
    """AC: events holds instance starts and shutdowns and ALTER SYSTEM / ALTER
    DATABASE commands, each with its record's time; a line written from a PDB keeps
    its command after the `<PDB>(<con_id>):` prefix. "Completed: ALTER ..." lines
    are not commands."""
    records = _raw()
    starts = _lines_matching(records, STARTUP_LINE)
    shutdowns = _lines_matching(records, SHUTDOWN_LINE)
    alters = [(t, ALTER_LINE.match(ln)) for t, ln in _lines_matching(records, ALTER_LINE)]
    kinds = {m.group(2) for _, m in alters}
    assert starts, "fixture: no timed startup (restart the instance before planting)"
    assert shutdowns, "fixture: no shutdown"
    assert kinds == {"SYSTEM", "DATABASE"}, f"fixture: ALTER kinds {kinds}"

    rows = _table(_extract_json(_fixture(), *ALL_ROWS), "events")
    assert {r["event"] for r in rows} == EVENT_KINDS
    got = {(r["time"], r["event"]) for r in rows}
    assert {(t, "startup") for t, _ in starts} <= got
    assert {(t, "shutdown") for t, _ in shutdowns} <= got
    for t, m in alters:
        kind = f"alter {m.group(2).lower()}"
        command = " ".join(m.group(1).split())
        texts = [" ".join(r["text"].split()) for r in rows if (r["time"], r["event"]) == (t, kind)]
        assert any(command[:TEXT_LIMIT] in text for text in texts), (t, command)
    assert not any(r["text"].lstrip().startswith("Completed:") for r in rows)
    times = [r["time"] for r in rows]
    assert times == sorted(times), "events not in time order"


def test_recent_errors_and_every_table_are_capped_with_a_dropped_count():
    """AC: recent_errors holds the last N records with an ORA- code (time, text cut to
    200 characters); each table holds at most --max-rows rows (default 20) and says
    how many were dropped."""
    records = _raw()
    with_ora = [(t, lines) for t, lines in records if any(ORA_CODE.search(ln) for ln in lines)]
    assert len(with_ora) > 3, "fixture: too few records with an ORA- code"

    full = _extract_json(_fixture(), *ALL_ROWS)
    capped = _extract_json(_fixture(), "--max-rows", "3")
    recent = _table(capped, "recent_errors")
    assert sorted(r["time"] for r in recent) == [t for t, _ in with_ora[-3:]]
    assert capped["sections"]["recent_errors"]["dropped"] == len(with_ora) - 3
    for row in recent:
        assert ORA_CODE.search(row["text"]) and len(row["text"]) <= TEXT_LIMIT, row

    default = _extract_json(_fixture())
    for name in SECTIONS:
        n = len(full["sections"][name]["rows"])
        assert full["sections"][name]["dropped"] == 0, name
        assert len(capped["sections"][name]["rows"]) == min(n, 3), name
        assert capped["sections"][name]["dropped"] == max(n - 3, 0), name
        assert len(default["sections"][name]["rows"]) == min(n, 20), name


def test_markdown_default_output_is_capped_and_states_dropped_rows():
    """AC: Markdown is the default: the summary first, then a heading per table; on
    the committed fixture the output stays under 30,000 characters; with
    --max-rows 1 each truncated table is followed by a line saying how many rows
    were dropped."""
    summary = _extract_json(_fixture())["summary"]
    result = _run_tools("extract-alert-log", str(_fixture()))
    assert result.returncode == 0, result.stderr
    text = result.stdout
    assert len(text) < OUTPUT_LIMIT, f"{len(text)} characters"
    starts = {name: text.find(f"\n## {name}") for name in SECTIONS}
    assert all(at > 0 for at in starts.values()), starts
    first = min(starts.values())
    for key in ("first_time", "last_time"):
        assert 0 <= text.find(summary[key]) < first, f"summary {key} not before the tables"
    tables = _md_tables(text)
    assert len(tables) >= len(SECTIONS) and max(rows for rows, _ in tables) <= 20

    full = _extract_json(_fixture(), *ALL_ROWS)["sections"]
    truncated = sum(len(table["rows"]) > 1 for table in full.values())
    assert truncated, "no table over 1 row: the cap is not exercised"
    result = _run_tools("extract-alert-log", str(_fixture()), "--max-rows", "1")
    assert result.returncode == 0, result.stderr
    tables = _md_tables(result.stdout)
    assert max(rows for rows, _ in tables) <= 1
    assert sum(bool(DROPPED_LINE.search(f)) for _, f in tables) == truncated


def test_long_message_lines_are_cut_to_200_characters(tmp_path):
    """AC: the ora_errors message and the recent_errors text are cut to 200
    characters. A copy of the fixture gets 500 extra characters on the first
    planted ORA-20281 line."""
    lines = _fixture().read_text(encoding="utf-8").splitlines(keepends=True)
    at = next(i for i, ln in enumerate(lines) if "ORA-20281" in ln)
    assert len(lines[at]) < 150, f"fixture: planted line too long to show the cut: {lines[at]!r}"
    lines[at] = lines[at].rstrip("\n") + "x" * 500 + "\n"
    long_log = tmp_path / "alert_long.log"
    long_log.write_text("".join(lines), encoding="utf-8")

    out = _extract_json(long_log, *ALL_ROWS)
    row = next(r for r in _table(out, "ora_errors") if r["code"] == "ORA-20281")
    assert len(row["message"]) <= TEXT_LIMIT and "x" * 50 in row["message"], row["message"]
    texts = [r["text"] for r in _table(out, "recent_errors")]
    assert max(len(t) for t in texts) <= TEXT_LIMIT
    assert all(len(r["text"]) <= TEXT_LIMIT for r in _table(out, "events"))


def test_not_an_alert_log_exits_1_and_bad_input_exits_2(tmp_path):
    """AC: a file that is not an alert log (an AWR or ASH report, plain text with
    ORA- codes but no timestamp line) exits 1 with "not an alert log"; a missing
    file or a bad option exits 2."""
    notes = tmp_path / "notes.txt"
    notes.write_text(
        "ORA-00600: internal error code\n*** 2026-11-13T14:53:50.398530+00:00\n"
        "Starting ORACLE instance (normal)\n",
        encoding="utf-8",
    )
    for bogus in (*OTHER_REPORTS, notes):
        assert bogus.is_file(), bogus
        result = _run_tools("extract-alert-log", str(bogus))
        assert result.returncode == 1, (bogus.name, result.returncode, result.stderr)
        assert "not an alert log" in result.stderr, bogus.name

    fixture = str(_fixture())
    for args in (
        [str(tmp_path / "missing.log")],
        [fixture, "--max-rows", "0"],
        [fixture, "--format", "xml"],
        [fixture, "--since", "2026-13-01"],
        [fixture, "--since", "yesterday"],
    ):
        result = _run_tools("extract-alert-log", *args)
        assert result.returncode == 2, (args, result.returncode, result.stderr)


