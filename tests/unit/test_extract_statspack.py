def test_json_summary_matches_the_snapshot_header_of_the_committed_fixture():
    """AC: summary carries database, instance, release, begin and end snapshot ids and
    times, elapsed and DB time, each equal to the report's header. The PDB report's
    Database column is blank, so db_name comes from the "DB/Inst: FREE/FREE" titles.
    The fixture's host name is `testhost`."""
    summary = _extract_json(_fixture())["summary"]

    assert list(summary) == SUMMARY_KEYS
    for key in SUMMARY_KEYS:
        assert summary[key] not in (None, ""), f"summary.{key} is empty"
    assert summary["db_name"] == CONTAINER_DB_NAME

    _db_id, instance, release = _raw("instance_line")
    assert summary["instance"] == instance == CONTAINER_DB_NAME
    assert summary["release"] == release

    begin_id, begin_time = _raw("begin_snap")
    end_id, end_time = _raw("end_snap")
    assert (summary["begin_snap_id"], summary["begin_time"]) == (begin_id, begin_time)
    assert (summary["end_snap_id"], summary["end_time"]) == (end_id, end_time)
    assert int(end_id) > int(begin_id)
    assert summary["elapsed"].split()[0] == _raw("elapsed")[0]
    assert summary["db_time"].split()[0] == _raw("db_time")[0]

    assert _raw("host") == ("testhost",)


def test_sections_are_found_by_exact_title_with_values_from_the_fixture():
    """AC: load_profile, top_events ("Top 5 Timed Events", as measured on 23ai),
    instance_efficiency and init_params are found by title, and their values are the
    report's: the Logical reads per-second figure, every top event in order, every
    efficiency indicator, every parameter name (a value wrapped onto the next line,
    such as control_files, stays one row)."""
    out = _extract_json(_fixture(), "--max-rows", "100000")
    statspack = importlib.import_module("tools.offline.statspack")
    assert set(TITLES) <= set(statspack.SECTIONS)
    assert set(out["sections"]) | set(out["sections_not_found"]) == set(statspack.SECTIONS)
    for name in TITLES:
        assert name not in out["sections_not_found"], f"{name} not found"
        assert out["sections"][name]["rows"], f"{name} has no rows"
    sections = out["sections"]

    # load_profile: "   Logical reads:            2,811.3            5,622.7"
    load = sections["load_profile"]
    assert load["columns"][0].strip()
    labels = [_norm(row[0]).rstrip(":") for row in load["rows"]]
    assert "Logical reads" in labels, labels
    per_second = _column(load, "Per Second")[labels.index("Logical reads")]
    raw = re.search(r"^\s*Logical reads:\s+([\d,.]+)", "\n".join(_lines()), re.MULTILINE)
    assert raw and per_second == raw.group(1)

    # top_events: event names cut at the width of the first column underline
    underline, block = _raw_blocks(TITLES["top_events"])[0]
    width = len(underline.split()[0])
    raw_rows = [ln for ln in block if ln.strip()]
    assert raw_rows, "no rows under Top 5 Timed Events in the raw fixture"
    events = _column(sections["top_events"], "Event")
    assert events == [ln[:width].strip() for ln in raw_rows]
    waits = _column(sections["top_events"], "Waits")
    for event, wait, line in zip(events, waits, raw_rows, strict=True):
        rest = line[width:].split()
        if wait:
            assert rest and wait == rest[0], (event, wait, line)

    # instance_efficiency: label: value pairs up to the first blank line
    lines = _lines()
    t = next(i for i, ln in enumerate(lines) if ln == TITLES["instance_efficiency"])
    pairs = []
    for line in lines[t + 2 :]:
        if not line.strip():
            break
        pairs += [[_norm(k), v] for k, v in PAIR.findall(line)]
    efficiency = sections["instance_efficiency"]
    assert efficiency["columns"] == PAIR_COLUMNS
    assert [[_norm(k), v] for k, v in efficiency["rows"]] == pairs
    assert any(k == "Library Hit %" for k, _ in pairs), pairs

    # init_params: one row per non-blank Parameter Name, wrapped values joined
    params = sections["init_params"]
    assert params["columns"][:2] == ["Parameter Name", "Begin value"]
    underline, block = _raw_blocks(TITLES["init_params"])[0]
    width = len(underline.split()[0])
    begin_at = len(underline) - len(underline[width:].lstrip())
    begin_end = begin_at + len(underline[begin_at:].split()[0])
    raw_params, wrapped = [], set()
    for line in (ln for ln in block if ln.strip()):
        name, value = line[:width].strip(), line[begin_at:begin_end].strip()
        if name:
            raw_params.append([name, value])
        else:
            raw_params[-1][1] += value
            wrapped.add(raw_params[-1][0])
    assert [row[0] for row in params["rows"]] == [n for n, _ in raw_params]
    assert wrapped, "no wrapped parameter value in the fixture (control_files wraps on 23ai)"
    values = {row[0]: row[1] for row in params["rows"]}
    for name, value in raw_params:
        assert values[name].replace(" ", "") == value.replace(" ", ""), name
    assert values["db_name"] == CONTAINER_DB_NAME


def test_sql_sections_hold_every_record_across_page_breaks():
    """AC: sql_by_elapsed, sql_by_cpu, sql_by_gets and sql_by_reads hold every record of
    their section, on every page, in report order, each with its SQL text.
    Falsifier (the case named in the issue): a long SQL section repeats its title on
    the next page (in the probe, sql_by_reads). Take only the table under the first
    matching title and that section's hash list comes up short; match a looser title
    ("SQL ordered by" + next word, or the "DB/Inst:" form only) and sql_by_elapsed,
    whose title has no "DB/Inst:", is lost or reads another table. A SQL text cut by
    the page break must join its record, never become a row of its own."""
    sections = _extract_json(_fixture(), "--max-rows", "100000")["sections"]
    continued = []
    for name in SQL_SECTIONS:
        blocks = _raw_blocks(TITLES[name])
        if len(blocks) > 1:
            continued.append(name)
        raw_hashes, first_text, tails = [], None, []
        for page, (_, block) in enumerate(blocks):
            records = [ln for ln in block if _is_numbers_line(ln)]
            raw_hashes += [ln.split()[-1] for ln in records]
            if page and block and block[0].strip() and not _is_numbers_line(block[0]):
                tails.append(block[0].strip())  # SQL text continued from the last page
            if first_text is None and records:
                k = block.index(records[0]) + 1
                while block[k].lstrip().startswith("Module:"):
                    k += 1
                first_text = block[k].strip()

        table = sections[name]
        hash_col = next((c for c in table["columns"] if c.endswith("Hash Value")), None)
        assert hash_col, f"{name}: no Hash Value column in {table['columns']}"
        hashes = _column(table, hash_col)
        assert hashes == raw_hashes, name
        assert all(h.isdigit() for h in hashes), f"{name}: rows that are not records"

        texts = [_norm(t) for t in _column(table, "SQL Text")]
        assert texts[0].startswith(_norm(first_text)), (name, texts[0], first_text)
        squeezed = [t.replace(" ", "") for t in texts]
        for tail in tails:
            assert any(tail.replace(" ", "") in t for t in squeezed), (name, tail)

    assert continued, "no SQL section continues on a second page: the fixture needs more SQL"


def test_markdown_default_output_summary_first_titles_and_caps():
    """AC: default output is Markdown: the summary first, then each section under
    "## <name>: <title>" with the exact title measured from the report (not the rest
    of the title line); no table over the default 20 rows; with --max-rows 1 each
    truncated table is followed by a line stating how many rows were dropped."""
    path = _fixture()
    summary = _extract_json(path)["summary"]

    result = _run_tools("extract-statspack", str(path))
    assert result.returncode == 0, result.stderr
    text = result.stdout
    assert len(text) < 30_000, f"{len(text)} characters"
    for name, title in TITLES.items():
        assert f"\n## {name}: {title}\n" in text, f"no heading for {name}"
    first_section_at = min(text.find(f"\n## {name}: ") for name in TITLES)
    for key in ("begin_snap_id", "end_snap_id", "begin_time", "db_name"):
        assert 0 <= text.find(summary[key]) < first_section_at, f"summary {key} not first"
    tables = _md_tables(text)
    assert tables and max(rows for rows, _ in tables) <= 20

    full = _extract_json(path, "--max-rows", "100000")["sections"]
    capped = _extract_json(path, "--max-rows", "1")["sections"]
    truncated = 0
    for name, table in capped.items():
        assert len(table["rows"]) <= 1, name
        assert table["dropped"] == max(len(full[name]["rows"]) - 1, 0), name
        truncated += bool(table["dropped"])
    assert truncated, "no table over 1 row: the cap is not exercised"

    result = _run_tools("extract-statspack", str(path), "--max-rows", "1")
    assert result.returncode == 0, result.stderr
    tables = _md_tables(result.stdout)
    assert max(rows for rows, _ in tables) <= 1
    assert sum(bool(DROPPED_LINE.search(f)) for _, f in tables) == truncated


def test_sections_option_selects_and_missing_sections_are_listed_not_fatal(tmp_path):
    """AC: --sections limits the output; a section absent from the report is listed
    under "Sections not found" and is not fatal. The real report cut just before its
    "init.ora Parameters" title keeps the header and loses init_params."""
    out = _extract_json(_fixture(), "--sections", "top_events,sql_by_gets")
    assert set(out["sections"]) == {"top_events", "sql_by_gets"}
    assert out["sections_not_found"] == []

    raw = _fixture().read_text(encoding="utf-8").split("\n")
    cut = next(i for i, ln in enumerate(raw) if _is_title(ln.lstrip("\f"), TITLES["init_params"]))
    partial = tmp_path / "partial_statspack.txt"
    partial.write_text("\n".join(raw[:cut]) + "\n")

    out = _extract_json(partial, "--sections", "load_profile,init_params")
    assert out["sections_not_found"] == ["init_params"]
    assert set(out["sections"]) == {"load_profile"}
    assert out["summary"]["begin_snap_id"] == _raw("begin_snap")[0]

    result = _run_tools("extract-statspack", str(partial))
    assert result.returncode == 0, result.stderr
    after = result.stdout.lower().split("sections not found", 1)
    assert len(after) == 2 and "init_params" in after[1]


def test_sql_text_cells_are_cut_to_200_characters(tmp_path):
    """AC: SQL text is cut to 200 characters. A copy of the fixture gets 500 extra
    characters on the first SQL text line of the first sql_by_gets record."""
    raw = _fixture().read_text(encoding="utf-8").split("\n")
    title = next(i for i, ln in enumerate(raw) if _is_title(ln.lstrip("\f"), TITLES["sql_by_gets"]))
    underline = next(i for i in range(title, len(raw)) if raw[i].startswith("---"))
    numbers = next(i for i in range(underline + 1, len(raw)) if _is_numbers_line(raw[i]))
    k = numbers + 1
    while raw[k].lstrip().startswith("Module:"):
        k += 1
    assert raw[k].strip(), "fixture changed: no SQL text under the first sql_by_gets record"
    raw[k] = raw[k] + "x" * 500
    long_report = tmp_path / "long_sql.txt"
    long_report.write_text("\n".join(raw))

    table = _extract_json(long_report, "--sections", "sql_by_gets")["sections"]["sql_by_gets"]
    cells = _column(table, "SQL Text")
    assert max(len(c) for c in cells) <= SQL_TEXT_LIMIT
    assert any("x" * 50 in c for c in cells), "the lengthened SQL text was not kept"


def test_not_a_statspack_report_exits_1_and_bad_input_exits_2(tmp_path):
    """AC: a file that is not a Statspack report (the AWR and ASH text reports, plain
    text naming Statspack sections) exits 1 with "not a Statspack report"; a missing
    file or a bad option exits 2."""
    notes = tmp_path / "notes.txt"
    notes.write_text(
        "STATSPACK notes\nLoad Profile is the first table.\nTop 5 Timed Events\n"
        "Begin Snap: 1\n"
    )
    for bogus in (*OTHER_REPORTS, notes):
        result = _run_tools("extract-statspack", str(bogus))
        assert result.returncode == 1, (bogus.name, result.returncode, result.stderr)
        assert "not a Statspack report" in result.stderr, bogus.name

    fixture = str(_fixture())
    for args in (
        [str(tmp_path / "missing.txt")],
        [fixture, "--sections", "top_events,bogus"],
        [fixture, "--max-rows", "0"],
        [fixture, "--format", "xml"],
    ):
        result = _run_tools("extract-statspack", *args)
        assert result.returncode == 2, (args, result.returncode, result.stderr)


