"""DBA-30: offline ASH extractor (`python -m tools extract-ash`) and the shared
extractor rendering in tools/offline/render.py.

No database is touched. The input is the committed ASH report pair
tests/fixtures/offline/ash_23ai_free.{html,txt}, generated by
tests/support/make_ash_fixture.py from the Oracle 23ai Free test container. Those
files do not exist until /implement generates them; tests that need them fail with
"fixture not found".

Measured by /tdd-prep on 2026-11-13 from a probe report of the test container
(gvenzl/oracle-free:23.26.3-slim-faststart, FREEPDB1 as SYSTEM, dbid = con_dbid):
both `dbms_workload_repository.ash_report_text` and `ash_report_html` return a
report. Section titles, identical in both formats:
  top_events   "Top User Events"          columns Event, Event Class, % Event, ...
  top_sql      "Top SQL with Top Events"  columns SQL ID, ..., SQL Text (HTML only;
               the text report prints the SQL text under each record)
  top_sessions "Top Sessions"             columns Sid,Srl# (Inst), % Activity, Event, ...
               (a later, different section is titled "Top Sessions running PQs")
  top_objects  "Top DB Objects"           columns Object ID, ..., Object Name (Type), ...
Summary: the header table (DB Name, Instance, Release, Host) and the lines
"Analysis Begin Time:", "Analysis End Time:", "Sample Count:",
"Average Active Sessions:". The HTML tables also carry a `summary` attribute; the
text report has nothing like it, so sections are found by title.
Top DB Objects only has rows when the workload waits on I/O against an object
(the probe flushed the buffer cache, then full-scanned its table).

Values are not hard-coded: the fixture is regenerated with a new window each time.
Each value test reads the number straight from the raw report with a narrow
pattern, and the HTML and text reports (same window) must agree.

JSON shape, the same as extract-awr:
  {"summary": {SUMMARY_KEYS...},
   "sections": {<name>: {"columns": [str], "rows": [[str]], "dropped": int}},
   "sections_not_found": [<name>]}

Implementation modules do not exist yet, so they are imported inside the tests:
each test fails on its own instead of the file erroring at collection.
"""

import ast
import html
import importlib
import inspect
import json
import re
import subprocess
import sys
from pathlib import Path
from types import SimpleNamespace

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURE_DIR = REPO_ROOT / "tests" / "fixtures" / "offline"
FIXTURES = {"html": FIXTURE_DIR / "ash_23ai_free.html", "txt": FIXTURE_DIR / "ash_23ai_free.txt"}
AWR_FIXTURES = {kind: FIXTURE_DIR / f"awr_23ai_free.{kind}" for kind in ("html", "txt")}
# extract-awr output captured from main 3dfd329, before the rendering moved.
AWR_EXPECTED_DIR = FIXTURE_DIR / "expected"
GENERATOR = REPO_ROOT / "tests" / "support" / "make_ash_fixture.py"
COMMANDS_DIR = REPO_ROOT / "tools" / "commands"

CONTAINER_DB_NAME = "FREE"  # DB name of the gvenzl/oracle-free CDB in tests/docker-compose.yml
REQUIRED_SECTIONS = {
    "top_events": "Top User Events",
    "top_sql": "Top SQL with Top Events",
    "top_sessions": "Top Sessions",
    "top_objects": "Top DB Objects",
}
KEY_COLUMN = {
    "top_events": "Event",
    "top_sql": "SQL ID",
    "top_sessions": "Sid,Srl# (Inst)",
    "top_objects": "Object Name (Type)",
}
SUMMARY_KEYS = [
    "db_name",
    "instance",
    "release",
    "begin_time",
    "end_time",
    "sample_count",
    "average_active_sessions",
]
SQL_TEXT_LIMIT = 200
SQL_ID = re.compile(r"[0-9a-z]{13}")
DROPPED_LINE = re.compile(r"\b(\d+)\b.*\bdropped\b|\bdropped\b.*\b(\d+)\b", re.IGNORECASE)

# Values straight from the raw report, one pattern per format.
RAW_PATTERNS = {
    "html": {
        "sample_count": r"Sample Count:\s*</td>\s*<td[^>]*>\s*([\d,]+)\s*<",
        "average_active_sessions": r"Average Active Sessions:\s*</td>\s*<td[^>]*>\s*([\d.,]+)\s*<",
    },
    "txt": {
        "sample_count": r"^\s*Sample Count:\s+([\d,]+)\s*$",
        "average_active_sessions": r"^\s*Average Active Sessions:\s+([\d.,]+)\s*$",
    },
}

if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))


def _run_tools(*args):
    return subprocess.run(
        [sys.executable, "-m", "tools", *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )


def _fixture(kind):
    path = FIXTURES[kind]
    assert path.is_file(), f"fixture not found: {path.relative_to(REPO_ROOT)}"
    return path


def _extract_json(path, *args):
    result = _run_tools("extract-ash", str(path), "--format", "json", *args)
    assert result.returncode == 0, f"exit {result.returncode}: {result.stderr}"
    return json.loads(result.stdout)


def _raw(kind, key):
    text = _fixture(kind).read_text(encoding="utf-8")
    match = re.search(RAW_PATTERNS[kind][key], text, re.MULTILINE)
    assert match, f"{key} not found in the raw {kind} fixture"
    return match.group(1)


def _column(table, name):
    assert name in table["columns"], f"no column {name!r} in {table['columns']}"
    i = table["columns"].index(name)
    return [row[i] for row in table["rows"]]


def _md_tables(text):
    """Split Markdown output into pipe tables: (data_rows, next_nonblank_line) per table."""
    lines = text.splitlines()
    tables, i = [], 0
    while i < len(lines):
        if lines[i].lstrip().startswith("|"):
            start = i
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                i += 1
            rows = [ln for ln in lines[start:i] if not re.fullmatch(r"\s*\|[\s:|-]*\|\s*", ln)]
            following = next((ln for ln in lines[i:] if ln.strip()), "")
            tables.append((len(rows) - 1, following))  # minus the header row
        else:
            i += 1
    return tables


