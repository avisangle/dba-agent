@pytest.mark.parametrize("kind", ["html", "txt"])
def test_a_report_compared_with_itself_shows_zero_difference_in_every_row(kind):
    """AC: a report compared with itself shows zero difference in every row; the
    summary sides are equal and carry DB time per elapsed second; no note, since the
    database and release match; the three sections use the pinned columns."""
    path = _fixture(FIXTURES_A[kind])
    out = _compare_json(path, path, *ALL_ROWS)
    summary, source = _source(path)

    assert set(out["sections"]) == set(SECTION_NAMES)
    for name in SECTION_NAMES:
        assert out["sections"][name]["columns"] == COLUMNS[name], name
        assert out["sections"][name]["rows"], f"{name} has no rows"
        assert out["sections"][name]["dropped"] == 0, name

    for side in ("first", "second"):
        for key in SUMMARY_KEYS:
            assert out["summary"][side][key] == summary[key], (side, key)
    expected_ratio = _minutes(summary["db_time"]) / _minutes(summary["elapsed"])
    for side in ("first", "second"):
        assert _close(_num(out["summary"][side]["db_time_per_second"]), expected_ratio, 0.01)
    assert out["notes"] == []

    load = _rows(out["sections"]["load_profile"])
    assert len(load) == len(source["load_profile"])
    for row in load:
        assert row["First per second"] == row["Second per second"], row
        assert _num(row["Difference"]) == 0, row
        if _num(row["First per second"]):
            assert _num(row["% change"]) == 0, row
        else:
            assert row["% change"] in ("", "0", "0.0", "0.00"), row

    events = _rows(out["sections"]["top_events"])
    assert {r["Event"] for r in events} == set(source["top_events"])
    for row in events:
        assert row["First time (s)"] == row["Second time (s)"], row
        assert row["First % DB time"] == row["Second % DB time"], row

    sql = _rows(out["sections"]["sql_by_elapsed"])
    assert {r["SQL Id"] for r in sql} == set(source["sql_by_elapsed"])
    for row in sql:
        assert row["First elapsed (s)"] == row["Second elapsed (s)"], row
        assert row["First executions"] == row["Second executions"], row


@pytest.mark.parametrize("kind", ["html", "txt"])
def test_fixture_pair_shows_the_differences_measured_from_the_two_files(kind):
    """AC: load_profile has each per-second figure from both reports, the difference
    SECOND minus FIRST and the % change against FIRST, sorted by absolute % change;
    top_events has every event of either report with time and % DB time in each,
    blank where absent, sorted by the larger time; sql_by_elapsed has every SQL id of
    either report with elapsed time and executions in each, SQL text cut to 200
    characters, sorted by the larger elapsed time. % change is blank when FIRST is 0.
    Falsifier: swap FIRST and SECOND in the difference and the sign assertion fails."""
    first, second = _fixture(FIXTURES_A[kind]), _fixture(FIXTURES_B[kind])
    sum_a, src_a = _source(first)
    sum_b, src_b = _source(second)
    assert (sum_a["begin_snap_id"], sum_a["end_snap_id"]) != (
        sum_b["begin_snap_id"],
        sum_b["end_snap_id"],
    ), "the second fixture pair must come from a different snapshot window"

    out = _compare_json(first, second, *ALL_ROWS)
    assert out["notes"] == []  # same database and release
    for key in SUMMARY_KEYS:
        assert out["summary"]["first"][key] == sum_a[key], key
        assert out["summary"]["second"][key] == sum_b[key], key

    # load_profile
    load = _rows(out["sections"]["load_profile"])
    assert {_label(r["Statistic"]) for r in load} == set(src_a["load_profile"]) | set(
        src_b["load_profile"]
    )
    signed = 0
    for row in load:
        label = _label(row["Statistic"])
        cell_a = src_a["load_profile"].get(label, {}).get("Per Second", "")
        cell_b = src_b["load_profile"].get(label, {}).get("Per Second", "")
        assert row["First per second"] == cell_a, row
        assert row["Second per second"] == cell_b, row
        a, b = _num(cell_a), _num(cell_b)
        if a is None or b is None:
            assert row["Difference"] == "" and row["% change"] == "", row
            continue
        diff = _num(row["Difference"])
        assert _close(diff, b - a), (row, b - a)
        if abs(b - a) >= 0.1:
            assert (diff > 0) == (b > a) and diff != 0, f"wrong sign: {row}"
            signed += 1
        if a == 0:
            assert row["% change"] == "" or (b == 0 and _num(row["% change"]) == 0), row
        else:
            assert _close(_num(row["% change"]), (b - a) / a * 100), (row, (b - a) / a * 100)
    assert signed, "no load profile figure differs between the two windows"
    changes = [abs(_num(r["% change"])) for r in load if r["% change"]]
    _check_sorted_desc(changes, "load_profile |% change|")

    # top_events
    events = _rows(out["sections"]["top_events"])
    names = [r["Event"] for r in events]
    assert len(names) == len(set(names)), "an event appears twice"
    assert set(names) == set(src_a["top_events"]) | set(src_b["top_events"])
    for row in events:
        for side, src in (("First", src_a), ("Second", src_b)):
            cells = src["top_events"].get(row["Event"], {})
            assert row[f"{side} time (s)"] == cells.get("Total Wait Time (sec)", ""), row
            assert row[f"{side} % DB time"] == cells.get("% DB time", ""), row
    larger = [max(_num(r["First time (s)"]) or 0, _num(r["Second time (s)"]) or 0) for r in events]
    _check_sorted_desc(larger, "top_events larger time")

    # sql_by_elapsed
    sql = _rows(out["sections"]["sql_by_elapsed"])
    ids = [r["SQL Id"] for r in sql]
    assert len(ids) == len(set(ids)), "an SQL id appears twice"
    assert set(ids) == set(src_a["sql_by_elapsed"]) | set(src_b["sql_by_elapsed"])
    for row in sql:
        texts = set()
        for side, src in (("First", src_a), ("Second", src_b)):
            cells = src["sql_by_elapsed"].get(row["SQL Id"], {})
            assert row[f"{side} elapsed (s)"] == cells.get("Elapsed Time (s)", ""), row
            assert row[f"{side} executions"] == cells.get("Executions", ""), row
            if cells:
                texts.add(cells["SQL Text"][:SQL_TEXT_LIMIT])
        assert len(row["SQL Text"]) <= SQL_TEXT_LIMIT
        assert row["SQL Text"] in texts, row
    larger = [
        max(_num(r["First elapsed (s)"]) or 0, _num(r["Second elapsed (s)"]) or 0) for r in sql
    ]
    _check_sorted_desc(larger, "sql_by_elapsed larger elapsed time")


def _md_cells(line):
    cells = re.split(r"(?<!\\)\|", line.strip())[1:-1]
    return [c.strip().replace("\\|", "|") for c in cells]


def _md_tables(text):
    """Pipe tables in Markdown: (header cells, data rows, next non-blank line)."""
    lines = text.splitlines()
    tables, i = [], 0
    while i < len(lines):
        if lines[i].lstrip().startswith("|"):
            start = i
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                i += 1
            rows = [
                _md_cells(ln)
                for ln in lines[start:i]
                if not re.fullmatch(r"\s*\|[\s:|-]*\|\s*", ln)
            ]
            following = next((ln for ln in lines[i:] if ln.strip()), "")
            tables.append((rows[0], rows[1:], following, start))
        else:
            i += 1
    return tables


@pytest.mark.parametrize("kind", ["html", "txt"])
def test_json_and_markdown_hold_the_same_rows(kind):
    """AC: Markdown (the default) and JSON hold the same rows: every JSON section is a
    Markdown table with the same header and rows, and both summaries come before the
    first section table."""
    first, second = _fixture(FIXTURES_A[kind]), _fixture(FIXTURES_B[kind])
    out = _compare_json(first, second)

    result = _run_tools("compare-awr", str(first), str(second))
    assert result.returncode == 0, result.stderr
    text = result.stdout
    tables = _md_tables(text)

    starts = []
    for name in SECTION_NAMES:
        section = out["sections"][name]
        match = [t for t in tables if t[0] == section["columns"]]
        assert len(match) == 1, f"{name}: no single Markdown table with its header"
        _, rows, _, line_no = match[0]
        # a pipe-table cell cannot carry edge spaces
        assert rows == [[c.strip() for c in r] for r in section["rows"]], name
        starts.append(line_no)

    head = "\n".join(text.splitlines()[: min(starts)])
    for side in ("first", "second"):
        for key in ("db_name", "release", "begin_snap_id", "end_snap_id", "db_time"):
            assert out["summary"][side][key] in head, f"summary {side}.{key} not before sections"
        assert out["summary"][side]["db_time_per_second"] in head


@pytest.mark.parametrize("kind", ["html", "txt"])
def test_max_rows_caps_every_table_with_a_dropped_rows_line(kind):
    """AC: every table is capped at --max-rows (default 20) with a dropped-rows line."""
    first, second = _fixture(FIXTURES_A[kind]), _fixture(FIXTURES_B[kind])
    full = _compare_json(first, second, *ALL_ROWS)["sections"]
    default = _compare_json(first, second)["sections"]
    capped = _compare_json(first, second, "--max-rows", "3")["sections"]

    truncated = 0
    for name in SECTION_NAMES:
        total = len(full[name]["rows"])
        assert len(default[name]["rows"]) == min(total, 20), name
        assert default[name]["dropped"] == max(total - 20, 0), name
        assert capped[name]["rows"] == full[name]["rows"][:3], name
        assert capped[name]["dropped"] == max(total - 3, 0), name
        truncated += total > 3
    assert truncated, "no table over 3 rows: the cap is not exercised"

    result = _run_tools("compare-awr", str(first), str(second), "--max-rows", "3")
    assert result.returncode == 0, result.stderr
    sections = [t for t in _md_tables(result.stdout) if t[0] in COLUMNS.values()]
    assert len(sections) == len(SECTION_NAMES)
    assert all(len(rows) <= 3 for _, rows, _, _ in sections)
    dropped_lines = [following for _, _, following, _ in sections if DROPPED_LINE.search(following)]
    assert len(dropped_lines) == truncated


@pytest.mark.parametrize("change", ["database", "release"])
def test_different_database_or_release_is_noted_not_an_error(change, tmp_path):
    """AC: when the two reports are from different databases or releases a line says
    so; the comparison still runs (exit 0). The second report is a copy of the real
    HTML fixture with its DB name or release changed."""
    path = _fixture(FIXTURES_A["html"])
    source = path.read_text(encoding="utf-8")
    if change == "database":
        anchor = "<tr><td scope=\"row\" class='awrnc'>FREE</td><td align=\"right\" class='awrnc'>"
        assert anchor in source, "fixture changed: DB Name cell not found"
        changed = source.replace(anchor, anchor.replace(">FREE<", ">OTHERDB<"), 1)
        word, value = "database", "OTHERDB"
    else:
        assert "23.26.3.0.0" in source, "fixture changed: release not found"
        changed = source.replace("23.26.3.0.0", "23.26.4.0.0", 1)
        word, value = "release", "23.26.4.0.0"
    other = tmp_path / f"other_{change}.html"
    other.write_text(changed, encoding="utf-8")

    out = _compare_json(path, other)
    notes = " ".join(out["notes"])
    assert word in notes.lower() and value in notes, out["notes"]
    assert out["sections"]["load_profile"]["rows"]

    result = _run_tools("compare-awr", str(path), str(other))
    assert result.returncode == 0, result.stderr
    assert any(word in ln.lower() and value in ln for ln in result.stdout.splitlines()), (
        f"no Markdown line names the different {word}"
    )


def test_bad_inputs_exit_1_for_a_non_awr_file_and_2_for_a_missing_file_or_bad_option(tmp_path):
    """AC: a file that is not an AWR report exits 1 naming it (in either position); a
    missing file or a bad option exits 2."""
    _require_command()
    good = _fixture(FIXTURES_A["txt"])
    bogus = tmp_path / "not_awr_notes.txt"
    bogus.write_text("Load Profile is a heading in many documents.\nNothing else.\n")

    for args in ((bogus, good), (good, bogus)):
        result = _run_tools("compare-awr", *map(str, args))
        assert result.returncode == 1, (args, result.stderr)
        assert bogus.name in result.stderr and good.name not in result.stderr, result.stderr

    missing = tmp_path / "no_such_report.html"
    result = _run_tools("compare-awr", str(good), str(missing))
    assert result.returncode == 2, result.stderr
    assert missing.name in result.stderr

    for bad in (
        ["--max-rows", "0"],
        ["--max-rows", "many"],
        ["--format", "xml"],
    ):
        result = _run_tools("compare-awr", str(good), str(good), *bad)
        assert result.returncode == 2, (bad, result.stderr)
    result = _run_tools("compare-awr", str(good))
    assert result.returncode == 2, "one file only must be refused"


