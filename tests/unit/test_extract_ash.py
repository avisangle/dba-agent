def test_contract_for_dependents_dba38_dba43():
    """Contract for DBA-38 (Statspack extractor reuses tools/offline/render.py) and
    DBA-43 (skill text for `extract-ash`): the `extract-ash` command; the fixtures
    ash_23ai_free.{html,txt} with the host replaced by `testhost` and their generator;
    tools.offline.ash exporting SECTIONS, AshReport, NotAshReport, parse_ash(path);
    tools.offline.render exporting SQL_TEXT_LIMIT,
      capped(table, max_rows) -> {"columns": list, "rows": list, "dropped": int}
        (table: any object with .columns and .rows)
      markdown(heading, summary, sections, not_found) -> str
        (summary: {label: value}; sections: {name: (title, capped(...))};
         not_found: [name])."""
    command = importlib.import_module("tools.commands.extract_ash")
    assert command.NAME == "extract-ash"
    for attr in ("HELP", "add_arguments", "run"):
        assert hasattr(command, attr), attr
    help_out = _run_tools("--help")
    assert help_out.returncode == 0 and "extract-ash" in help_out.stdout

    ash = importlib.import_module("tools.offline.ash")
    assert inspect.isclass(ash.AshReport)
    assert issubclass(ash.NotAshReport, Exception)
    assert list(inspect.signature(ash.parse_ash).parameters) == ["path"]
    assert set(REQUIRED_SECTIONS) <= set(ash.SECTIONS)
    for path in FIXTURES.values():
        assert isinstance(ash.parse_ash(path), ash.AshReport)

    render = importlib.import_module("tools.offline.render")
    assert render.SQL_TEXT_LIMIT == SQL_TEXT_LIMIT
    assert list(inspect.signature(render.capped).parameters) == ["table", "max_rows"]
    table = render.capped(SimpleNamespace(columns=["a", "b"], rows=[["1", "2"], ["3", "4"]]), 1)
    assert isinstance(table["columns"], list)
    assert isinstance(table["rows"], list)
    assert isinstance(table["dropped"], int)
    params = list(inspect.signature(render.markdown).parameters)
    assert params == ["heading", "summary", "sections", "not_found"]
    assert isinstance(render.markdown("h", {"Label": "v"}, {"s": ("Title", table)}, ["t"]), str)

    assert GENERATOR.is_file()
    for path in FIXTURES.values():
        assert path.is_file() and path.stat().st_size > 0, path
        assert "testhost" in path.read_text(encoding="utf-8"), f"{path.name}: host not replaced"
