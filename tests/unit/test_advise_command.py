def test_advise_exit_codes_before_sqlcl_starts(tmp_path):
    """AC: exit 2 for an unknown id, a check whose mode is not A and a bad
    parameter; exit 1 for a check failing lint (L018: mode A with no
    SCRIPT_LINE alias, D-DBA-1). In each case no file is written and no SQLcl
    process is started."""
    exe, log = _fake_sqlcl(tmp_path / "fake", _script_result().text)

    for args, code, needle in (
        (["no_such_check"], 2, "no_such_check"),
        ([MODE_R_CHECK], 2, MODE_R_CHECK),
        ([str(MODE_A_CHECK), "--param", "owner=APP"], 2, "owner"),
        ([str(MODE_A_CHECK), "--param", "owner"], 2, "owner"),
        ([str(NO_SCRIPT_LINE)], 1, "L018"),
    ):
        proc = _advise(tmp_path, *args, "--connection", CONNECTION, sqlcl=exe)
        _command_exists(proc)
        assert proc.returncode == code, (args, proc.stdout, proc.stderr)
        assert needle in proc.stderr, (args, proc.stderr)
    assert _written(tmp_path) == []
    assert not log.exists(), "advise must refuse before starting SQLcl"


