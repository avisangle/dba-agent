"""DBA-28: offline alert log extractor (`python -m tools extract-alert-log`).

No database is touched. The input is the committed alert log
tests/fixtures/offline/alert_23ai_free.log, generated by
tests/support/make_alert_log_fixture.py from the Oracle 23ai Free test container.
Neither exists until /implement writes them; tests that need the fixture fail with
"fixture not found".

Measured by /tdd-prep on 2026-11-13 from the test container
(gvenzl/oracle-free:23.26.3-slim-faststart), file
/opt/oracle/diag/rdbms/free/FREE/trace/alert_FREE.log:
- A record starts with a line that is only an ISO 8601 timestamp,
  `2026-11-13T14:55:39.463471+00:00`. Lines such as
  `*** 2026-11-13T14:53:50.398530+00:00` (crash recovery) are not record starts.
- A fresh container's log starts with untimed lines: "Adjusting the default value
  ..." and "Starting ORACLE instance (normal) (OS id: 35)" come before the first
  timestamp. After `docker restart` the next startup is timed: the timestamp line,
  then "Adjusting ...", then "Starting ORACLE instance (normal)". So a fixture with a
  timed startup needs an instance restart before the planted lines.
- Shutdown: "Shutting down ORACLE instance (immediate)" ... "Instance shutdown
  complete". ALTER DATABASE lines ("ALTER DATABASE   MOUNT", "ALTER DATABASE OPEN",
  "ALTER DATABASE CLOSE NORMAL") come with "Completed: ALTER DATABASE ..." lines.
- `alter system set open_cursors=301 scope=memory` run as SYSDBA in FREEPDB1 logs
  `FREEPDB1(3):ALTER SYSTEM SET open_cursors=301 SCOPE=MEMORY PDB='FREEPDB1';`:
  lines written from a PDB carry a `<PDB>(<con_id>):` prefix.
- `sys.dbms_system.ksdwrt(2, ...)` as SYSDBA in FREEPDB1 writes " : " and then the
  text, each line prefixed `FREEPDB1(3):`; text with chr(10) becomes several lines
  of one record. Two ksdwrt calls a few milliseconds apart landed in ONE record
  (one timestamp), so the generator must space its plants to get one record each.
- `alter system switch logfile` gives ORA-65040 in a PDB; run six times quickly in
  the CDB root (service FREE, SYSDBA) it logs "Thread 1 advanced to log sequence N
  (LGWR switch)" per switch and, for most, "Thread 1 cannot allocate new log,
  sequence N" plus "Checkpoint not complete".
- Real ORA- lines in a fresh log: ORA-29701, ORA-00800 (twice), ORA-20013 and
  ORA-06512 four times in one record (DBMS_QOPATCH stack).
- The host name appears as "Node name:\t<host>" and in "oracle@<host>".

What the committed fixture must hold (the generator plants it; preconditions
below fail with a clear message otherwise):
- ORA-20281 in exactly 3 records, spread over at least two distinct minutes, and
  ORA-20282 in exactly 1 record on two of its lines; every planted line carries
  PLANT_TAG and is under 150 characters. Planted codes are in the user range, so
  nothing else writes them.
- At least one timed startup, one shutdown, one ALTER SYSTEM and one ALTER
  DATABASE line, one log switch and one "Checkpoint not complete".
- The host replaced by `testhost`.

Contract pinned here (the names /implement must use):
  --format json prints
    {"summary": {"first_time", "last_time", "records", "since", "window_records",
                 "log_switches", "checkpoint_not_complete"},
     "sections": {<name>: {"columns": [str], "rows": [[...]], "dropped": int}}}
  sections and their columns:
    ora_errors     code, count, first_time, last_time, message
    events         time, event, text   (event: startup, shutdown, alter system,
                                        alter database)
    recent_errors  time, text   (text holds an ORA- code within its 200 characters)
  Times are the record's timestamp line exactly as written in the log. `count` is
  the number of records holding the code: a record with the code on two lines
  counts once. `since` is the --since value or null; `window_records` the number of
  records at or after it (all records without --since); the three tables, the log
  switch and the checkpoint counts cover only that window.

Implementation modules do not exist yet, so they are imported inside the tests:
each test fails on its own instead of the file erroring at collection.
"""

import importlib
import json
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURE_DIR = REPO_ROOT / "tests" / "fixtures" / "offline"
FIXTURE = FIXTURE_DIR / "alert_23ai_free.log"
GENERATOR = REPO_ROOT / "tests" / "support" / "make_alert_log_fixture.py"
OTHER_REPORTS = [FIXTURE_DIR / "awr_23ai_free.txt", FIXTURE_DIR / "ash_23ai_free.html"]

PLANT_TAG = "dba28 planted"
PLANTED = {"ORA-20281": 3, "ORA-20282": 1}
TEXT_LIMIT = 200
OUTPUT_LIMIT = 30_000
SECTIONS = {
    "ora_errors": ["code", "count", "first_time", "last_time", "message"],
    "events": ["time", "event", "text"],
    "recent_errors": ["time", "text"],
}
SUMMARY_KEYS = {
    "first_time",
    "last_time",
    "records",
    "since",
    "window_records",
    "log_switches",
    "checkpoint_not_complete",
}
EVENT_KINDS = {"startup", "shutdown", "alter system", "alter database"}

# Narrow raw patterns, independent of the implementation.
TIMESTAMP_LINE = re.compile(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d\.\d+[+-]\d\d:\d\d")
ORA_CODE = re.compile(r"\bORA-\d{5}\b")
PDB_PREFIX = r"(?:[A-Za-z0-9$_#]+\(\d+\):)?"
ALTER_LINE = re.compile(rf"^{PDB_PREFIX}(ALTER (SYSTEM|DATABASE)\b.*)$")
STARTUP_LINE = re.compile(rf"^{PDB_PREFIX}Starting ORACLE instance\b")
SHUTDOWN_LINE = re.compile(rf"^{PDB_PREFIX}Shutting down ORACLE instance\b")
LOG_SWITCH_LINE = re.compile(r"^Thread \d+ advanced to log sequence \d+")
CHECKPOINT_LINE = re.compile(r"^Checkpoint not complete\s*$")
DROPPED_LINE = re.compile(r"\b(\d+)\b.*\bdropped\b|\bdropped\b.*\b(\d+)\b", re.IGNORECASE)
ALL_ROWS = ("--max-rows", "100000")

if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))


def _run_tools(*args):
    return subprocess.run(
        [sys.executable, "-m", "tools", *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )


def _fixture():
    assert FIXTURE.is_file(), f"fixture not found: {FIXTURE.relative_to(REPO_ROOT)}"
    return FIXTURE


def _extract_json(path, *args):
    result = _run_tools("extract-alert-log", str(path), "--format", "json", *args)
    assert result.returncode == 0, f"exit {result.returncode}: {result.stderr}"
    return json.loads(result.stdout)


def _records(text):
    """[(timestamp, [lines])] split at timestamp lines; lines before the first are not a record."""
    records = []
    for line in text.splitlines():
        if TIMESTAMP_LINE.fullmatch(line):
            records.append((line, []))
        elif records:
            records[-1][1].append(line)
    return records


def _raw():
    return _records(_fixture().read_text(encoding="utf-8"))


def _holding(records, code):
    return [(t, lines) for t, lines in records if any(code in ln for ln in lines)]


def _raw_ora_counts(records):
    counts = {}
    for _, lines in records:
        for code in {c for ln in lines for c in ORA_CODE.findall(ln)}:
            counts[code] = counts.get(code, 0) + 1
    return counts


def _lines_matching(records, pattern):
    return [(t, ln) for t, lines in records for ln in lines if pattern.search(ln)]


def _table(out, name):
    table = out["sections"][name]
    assert table["columns"] == SECTIONS[name], (name, table["columns"])
    return [dict(zip(table["columns"], row, strict=True)) for row in table["rows"]]


def _since(records):
    """A --since minute that splits the planted ORA-20281 records: the second distinct minute."""
    minutes = sorted({t[:16] for t, _ in _holding(records, "ORA-20281")})
    assert len(minutes) >= 2, f"fixture: planted ORA-20281 records must span two minutes: {minutes}"
    return minutes[1]


def _md_tables(text):
    """Split Markdown output into pipe tables: (data_rows, next_nonblank_line) per table."""
    lines = text.splitlines()
    tables, i = [], 0
    while i < len(lines):
        if lines[i].lstrip().startswith("|"):
            start = i
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                i += 1
            rows = [ln for ln in lines[start:i] if not re.fullmatch(r"\s*\|[\s:|-]*\|\s*", ln)]
            following = next((ln for ln in lines[i:] if ln.strip()), "")
            tables.append((len(rows) - 1, following))  # minus the header row
        else:
            i += 1
    return tables


