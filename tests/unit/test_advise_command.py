"""DBA-36: the mode A contract, `validate_script_result`, the `advise` command,
the harness running mode A checks as `adv`, and the files this story adds.

No database is touched. `advise` runs as `python -m tools advise` against the
fake SQLcl (tests/support/fake_sqlcl.py), whose scripted `run-sql` reply is a
mode A result. That fake is the seam for the file-order falsifier: a result
whose LINE_NO order differs from the alphabetical order of its SCRIPT_LINE
values (and from LINE_NO compared as text: 1, 2, 9, 10), so an `advise` that
sorts by SCRIPT_LINE, or by LINE_NO as a string, writes the wrong body.

The mode A check run here is tests/fixtures/checks/valid/storage/mode_a_script.sql;
the L018 fixtures are under tests/fixtures/checks/L018-*/ and are picked up by
tests/unit/test_check_lint.py::test_each_rule_fixture_reports_only_its_own_code.

Pinned for /implement:
- result columns `LINE_NO`, `SCRIPT_LINE` (CSV header names, upper case);
- the file is `<dir>/<id>-<YYYYmmdd-HHMMSS>.sql`, `<dir>` = `--out-dir` or
  `<pack_home>/scripts`; every line before the script body is a `--` comment
  or blank, and the body is the SCRIPT_LINE values, one per line, last in the
  file; the header holds the check id, the connection name, "UTC" and the
  sentence in GENERATED;
- stdout holds the file path and the line count; "nothing to do" for zero rows;
- the harness keeps `test_check(path, request)` and reaches the mode A session
  only through `request.getfixturevalue("adv")`.
"""

