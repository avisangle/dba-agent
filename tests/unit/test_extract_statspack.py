"""DBA-38: offline Statspack report extractor (`python -m tools extract-statspack`).

No database is touched. The input is the committed text report
tests/fixtures/offline/statspack_23ai_free.txt, generated by
tests/support/make_statspack_fixture.py from the Oracle 23ai Free test container
with Statspack installed in FREEPDB1 (tests/support/install_statspack.sh). That file
does not exist until /implement generates it; tests that need it fail with
"fixture not found".

Measured by /tdd-prep on 2026-11-13 from probe `spreport.sql` reports of the test
container (gvenzl/oracle-free:23.26.3-slim-faststart, Statspack in FREEPDB1, report
run as SYS in FREEPDB1 with begin_snap, end_snap and report_name defined):
- Snapshots must be taken from a real logon to the PDB (SqlclSession). Taken as SYS
  after `alter session set container`, the PDB's "logons current" is 0 and the
  report's snapshot header fails with ORA-01476 (no Begin Snap / End Snap lines,
  blank Per Second column in the Load Profile).
- Header: "STATSPACK report for", then a fixed-width table Database, DB Id, Instance,
  Inst Num, Startup Time, Release, RAC. In a PDB report the Database column is blank;
  every section title carries "DB/Inst: FREE/FREE". Then Host Name (the container
  id; the fixture replaces it with `testhost`), then the snapshot table:
      Begin Snap:          3 13-Nov-26 17:06:28        1       3.0
        End Snap:          4 13-Nov-26 17:06:34        1       5.0
         Elapsed:       0.10 (mins) Av Act Sess:       0.1
         DB time:       0.01 (mins)      DB CPU:       0.01 (mins)
- Section titles (section name -> exact title):
    load_profile         "Load Profile" (title and column headers on one line)
    instance_efficiency  "Instance Efficiency Indicators" (label: value pairs, two per line)
    top_events           "Top 5 Timed Events" (the 23ai Statspack title)
    sql_by_cpu           "SQL ordered by CPU  DB/Inst: ..."
    sql_by_elapsed       "SQL ordered by Elapsed time for DB: FREE  Instance: FREE  Snaps: 3 -4"
                         (no "DB/Inst:" in this one title)
    sql_by_gets          "SQL ordered by Gets  DB/Inst: ..."
    sql_by_reads         "SQL ordered by Reads  DB/Inst: ..."
    init_params          "init.ora Parameters  DB/Inst: ..." (long values such as
                         control_files wrap onto lines with a blank Parameter Name)
- Pages are 60 lines. A page starts with a form feed glued to the title line
  ("\\fSQL ordered by Reads  DB/Inst: ..."; str.splitlines() splits at it, so it
  yields an empty line, then the title). A section longer than a page repeats its
  title, notes and column header on the next page, and a SQL record cut by the page
  break continues there before the next numbers line.
- SQL sections: one numbers line per record ending in the hash value (headed
  "Old Hash Value" or "Hash Value"), then "Module: ..." and the SQL text wrapped at
  64 characters, records separated by blank lines.

Values are not hard-coded: the fixture is regenerated with new snapshots each time.
Each value test reads the number straight from the raw report.

JSON shape, the same as extract-awr and extract-ash:
  {"summary": {SUMMARY_KEYS...},
   "sections": {<name>: {"columns": [str], "rows": [[str]], "dropped": int}},
   "sections_not_found": [<name>]}

Implementation modules do not exist yet, so they are imported inside the tests:
each test fails on its own instead of the file erroring at collection.
"""

