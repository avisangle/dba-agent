@pytest.mark.parametrize("kind", ["html", "txt"])
def test_json_summary_and_sections_match_the_committed_fixture(kind):
    """AC: summary carries database, instance, release, analysis begin and end time,
    sample count and average active sessions, with the sample count and average
    active sessions equal to the numbers printed in the report; top_events,
    top_sql, top_sessions and top_objects are found by title with rows.
    Falsifier: match sections by the HTML `summary` attribute only and the txt case
    fails (the text report has no such attribute)."""
    out = _extract_json(_fixture(kind))

    summary = out["summary"]
    for key in SUMMARY_KEYS:
        assert summary.get(key) not in (None, ""), f"summary.{key} is empty"
    assert summary["db_name"] == CONTAINER_DB_NAME
    assert summary["sample_count"] == _raw(kind, "sample_count")
    assert int(summary["sample_count"].replace(",", "")) > 0
    assert summary["average_active_sessions"] == _raw(kind, "average_active_sessions")

    for name, column in KEY_COLUMN.items():
        assert name not in out["sections_not_found"], f"{name} not found"
        table = out["sections"][name]
        assert table["rows"], f"{name} has no rows"
        assert any(_column(table, column)), f"{name}.{column} is empty in every row"

    sql_ids = [s for s in _column(out["sections"]["top_sql"], "SQL ID") if s]
    assert sql_ids and all(SQL_ID.fullmatch(s) for s in sql_ids), sql_ids

    ash = importlib.import_module("tools.offline.ash")
    assert set(out["sections"]) | set(out["sections_not_found"]) == set(ash.SECTIONS)


def test_html_and_text_reports_agree_on_summary_top_event_and_sql_ids():
    """AC: values read from the committed fixture in both formats. The two reports
    cover the same window, so the summary values, the top event with its
    percentage, every % Event value and the SQL ids of top_sql must agree; the top
    event's name and percentage sit on one line of the raw text report."""
    out = {kind: _extract_json(_fixture(kind), "--max-rows", "100000") for kind in FIXTURES}

    for key in ("db_name", "begin_time", "end_time", "sample_count", "average_active_sessions"):
        assert out["html"]["summary"][key] == out["txt"]["summary"][key], key

    events = {kind: out[kind]["sections"]["top_events"] for kind in FIXTURES}
    top = {kind: (_column(t, "Event")[0], _column(t, "% Event")[0]) for kind, t in events.items()}
    assert top["html"] == top["txt"]
    event, percent = top["txt"]
    assert re.fullmatch(r"\d+\.\d\d", percent), percent
    raw_lines = _fixture("txt").read_text(encoding="utf-8").splitlines()
    assert any(ln.startswith(event) and percent in ln.split() for ln in raw_lines), (event, percent)
    assert _column(events["html"], "% Event") == _column(events["txt"], "% Event")

    def sql_ids(kind):
        ids = _column(out[kind]["sections"]["top_sql"], "SQL ID")
        return list(dict.fromkeys(s for s in ids if s))

    assert sql_ids("html") == sql_ids("txt")

    # The text report prints each statement's SQL text under its record.
    top_sql = out["txt"]["sections"]["top_sql"]
    col = next(i for i, c in enumerate(top_sql["columns"]) if "sql text" in c.lower())
    first_text = top_sql["rows"][0][col]
    assert first_text, "text top_sql: first row has no SQL text"
    raw = " ".join(" ".join(raw_lines).split())
    assert " ".join(first_text.split())[:40] in raw


@pytest.mark.parametrize("kind", ["html", "txt"])
def test_markdown_default_output_summary_first_titles_and_caps(kind):
    """AC: default output is Markdown: the summary first (sample count before any
    section), then each section under "## <name>: <title>" with the title measured
    from the report; no table over the default 20 rows; with --max-rows 1 each
    truncated table is followed by a line stating how many rows were dropped."""
    path = _fixture(kind)
    summary = _extract_json(path)["summary"]

    result = _run_tools("extract-ash", str(path))
    assert result.returncode == 0, result.stderr
    text = result.stdout
    assert len(text) < 30_000, f"{len(text)} characters"
    first_section_at = text.find("\n## top_")
    assert first_section_at > 0, "no top_* section heading in the Markdown output"
    for key in ("db_name", "sample_count", "average_active_sessions", "begin_time"):
        assert 0 <= text.find(summary[key]) < first_section_at, f"summary {key} not first"
    for name, title in REQUIRED_SECTIONS.items():
        assert f"\n## {name}: {title}\n" in text, f"no heading for {name}"
    sessions = text.split("\n## top_sessions: ", 1)[1].split("\n## ", 1)[0]
    assert "running PQs" not in sessions, "top_sessions matched Top Sessions running PQs"
    tables = _md_tables(text)
    assert tables and max(rows for rows, _ in tables) <= 20

    full = _extract_json(path, "--max-rows", "100000")["sections"]
    capped = _extract_json(path, "--max-rows", "1")["sections"]
    truncated = 0
    for name, table in capped.items():
        assert len(table["rows"]) <= 1, name
        assert table["dropped"] == max(len(full[name]["rows"]) - 1, 0), name
        truncated += bool(table["dropped"])
    assert truncated, "no table over 1 row: the cap is not exercised"

    result = _run_tools("extract-ash", str(path), "--max-rows", "1")
    assert result.returncode == 0, result.stderr
    tables = _md_tables(result.stdout)
    assert max(rows for rows, _ in tables) <= 1
    assert sum(bool(DROPPED_LINE.search(f)) for _, f in tables) == truncated


def test_sections_option_selects_and_missing_sections_are_listed_not_fatal(tmp_path):
    """AC: --sections limits the output; a section absent from the report is listed
    under "Sections not found" and is not fatal. The real text report cut just
    before its "Top DB Objects" title keeps the header and loses top_objects."""
    out = _extract_json(_fixture("html"), "--sections", "top_events,top_sql")
    assert set(out["sections"]) == {"top_events", "top_sql"}
    assert out["sections_not_found"] == []

    lines = _fixture("txt").read_text(encoding="utf-8").splitlines(keepends=True)
    cut = next(i for i, ln in enumerate(lines) if ln.startswith(REQUIRED_SECTIONS["top_objects"]))
    partial = tmp_path / "partial_ash.txt"
    partial.write_text("".join(lines[:cut]))

    out = _extract_json(partial, "--sections", "top_events,top_objects")
    assert out["sections_not_found"] == ["top_objects"]
    assert set(out["sections"]) == {"top_events"}
    assert out["summary"]["db_name"] == CONTAINER_DB_NAME

    result = _run_tools("extract-ash", str(partial))
    assert result.returncode == 0, result.stderr
    after = result.stdout.lower().split("sections not found", 1)
    assert len(after) == 2 and "top_objects" in after[1]


def test_sql_text_cells_are_cut_to_200_characters(tmp_path):
    """AC: top_sql SQL text is cut to 200 characters. A copy of the HTML fixture gets
    500 extra characters in the first SQL text cell of Top SQL with Top Events."""
    path = _fixture("html")
    top_sql = _extract_json(path, "--sections", "top_sql")["sections"]["top_sql"]
    col = next(i for i, c in enumerate(top_sql["columns"]) if "sql text" in c.lower())
    anchor = top_sql["rows"][0][col][:30]
    assert anchor, "first top_sql row has an empty SQL text"

    source = path.read_text(encoding="utf-8")
    start = source.index(REQUIRED_SECTIONS["top_sql"] + "<")
    candidates = (anchor, html.escape(anchor, quote=False))
    found = next((a for a in candidates if a in source[start:]), None)
    assert found, f"SQL text {anchor!r} not located after the top_sql title"
    at = source.index(found, start) + len(found)
    long_report = tmp_path / "long_sql.html"
    long_report.write_text(source[:at] + "x" * 500 + source[at:])

    out = _extract_json(long_report, "--sections", "top_sql")
    cells = [row[col] for row in out["sections"]["top_sql"]["rows"]]
    assert max(len(c) for c in cells) <= SQL_TEXT_LIMIT
    assert any("x" * 50 in c for c in cells), "the lengthened SQL text was not kept"


def test_not_an_ash_report_exits_1_and_bad_input_exits_2(tmp_path):
    """AC: a file that is not an ASH report (an AWR report, a plain page, plain text)
    exits 1 with "not an ASH report"; a missing file or a bad option exits 2."""
    page = tmp_path / "page.html"
    page.write_text(
        "<html><body><h3>Top User Events</h3><table><tr><th>Event</th></tr>"
        "<tr><td>x</td></tr></table></body></html>"
    )
    notes = tmp_path / "notes.txt"
    notes.write_text("Top User Events is a heading in many documents.\nSample Count: 3\n")
    for bogus in (AWR_FIXTURES["html"], AWR_FIXTURES["txt"], page, notes):
        result = _run_tools("extract-ash", str(bogus))
        assert result.returncode == 1, (bogus.name, result.returncode, result.stderr)
        assert "not an ASH report" in result.stderr, bogus.name

    fixture = str(_fixture("html"))
    for args in (
        [str(tmp_path / "missing.html")],
        [fixture, "--sections", "top_events,bogus"],
        [fixture, "--max-rows", "0"],
        [fixture, "--format", "xml"],
    ):
        result = _run_tools("extract-ash", *args)
        assert result.returncode == 2, (args, result.returncode, result.stderr)


