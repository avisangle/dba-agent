def test_contract_for_dependent_dba18():
    """Contract for DBA-18 (packages the skill and command): `extract-awr` command,
    plugin/skills/offline-analysis/SKILL.md, fixtures under tests/fixtures/offline/,
    and tools.offline.awr exporting AwrReport, parse_awr(path) -> AwrReport, SECTIONS."""
    command = importlib.import_module("tools.commands.extract_awr")
    assert command.NAME == "extract-awr"
    for attr in ("HELP", "add_arguments", "run"):
        assert hasattr(command, attr), attr

    help_out = _run_tools("--help")
    assert help_out.returncode == 0 and "extract-awr" in help_out.stdout

    awr = importlib.import_module("tools.offline.awr")
    assert inspect.isclass(awr.AwrReport)
    assert list(inspect.signature(awr.parse_awr).parameters) == ["path"]
    assert list(awr.SECTIONS) == ALL_SECTIONS
    for path in FIXTURES.values():
        assert isinstance(awr.parse_awr(path), awr.AwrReport)

    assert SKILL.is_file()
    assert GENERATOR.is_file()
    for path in FIXTURES.values():
        assert path.is_file() and path.stat().st_size > 0, path
        assert "testhost" in path.read_text(), f"{path.name}: host name not replaced"
