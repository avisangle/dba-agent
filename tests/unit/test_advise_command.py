def test_contract_for_dependents_dba40_dba42():
    """Contract for DBA-40 (mode A contract, harness and `advise`) and DBA-42
    (advisory rules). Shape only: validate_script_result(check, result) ->
    list[str] in tools/checks/run.py; lint code L018; the `advise` command and
    its options; the advisory tier's sixth object grant; the two checks as mode
    A files; the advisory playbook; the harness signature."""
    run = importlib.import_module("tools.checks.run")
    assert list(inspect.signature(run.validate_script_result).parameters) == ["check", "result"]
    assert isinstance(run.validate_script_result(parse_check(MODE_A_CHECK), _script_result()),
                      list)
    assert list(inspect.signature(run.validate_result).parameters) == ["check", "result"]

    from tools.checks.lint import lint_file
    assert {f.code for f in lint_file(NO_SCRIPT_LINE)} == {"L018"}

    commands = {m.NAME: m for m in importlib.import_module("tools.__main__").discover_commands()}
    assert "advise" in commands
    advise = importlib.import_module("tools.commands.advise")
    assert advise.NAME == "advise" and isinstance(advise.HELP, str)
    assert callable(advise.add_arguments) and callable(advise.run)
    parser = argparse.ArgumentParser()
    advise.add_arguments(parser)
    args = parser.parse_args(["reclaimable_space", "--connection", "c", "--tier", "advisory",
                              "--home", "h", "--param", "a=1", "--param", "b=2",
                              "--out-dir", "d"])
    assert (args.connection, args.param) == ("c", ["a=1", "b=2"])
    assert Path(args.home) == Path("h") and Path(args.out_dir) == Path("d")
    from tools.tiers import TIERS
    assert args.tier == TIERS["advisory"]
    defaults = parser.parse_args(["reclaimable_space", "--connection", "c"])
    assert defaults.tier == TIERS["advisory"] and defaults.home is None
    assert defaults.out_dir is None and defaults.param is None

    assert NEW_GRANT in TIERS["advisory"].object_grants
    for path in (RECLAIMABLE, RESTORE):
        assert parse_check(path).mode == "A"
    assert PLAYBOOK.is_file()

    harness = importlib.import_module("test_all_checks")
    assert list(inspect.signature(harness.test_check).parameters) == ["path", "request"]
