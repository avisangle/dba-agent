def test_contract_for_dependent_dba43():
    """Contract for DBA-43 (skill text for `extract-statspack`): the command
    `python -m tools extract-statspack FILE [--sections a,b] [--max-rows N]
    [--format md|json]`, listed in `--help`, rendering through tools/offline/render.py
    (a source scan: which module a command delegates to has no behavioural seam); the
    fixture statspack_23ai_free.txt with the host replaced by `testhost`, and its
    generator; tools.offline.statspack exporting SECTIONS, StatspackReport,
    NotStatspackReport and parse_statspack(path)."""
    command = importlib.import_module("tools.commands.extract_statspack")
    assert command.NAME == "extract-statspack"
    for attr in ("HELP", "add_arguments", "run"):
        assert hasattr(command, attr), attr
    help_out = _run_tools("--help")
    assert help_out.returncode == 0 and "extract-statspack" in help_out.stdout
    options = _run_tools("extract-statspack", "--help")
    assert options.returncode == 0
    for option in ("--sections", "--max-rows", "--format"):
        assert option in options.stdout, option

    tree = ast.parse(COMMAND_FILE.read_text(encoding="utf-8"))
    imports = {n.module for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)} | {
        a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names
    }
    assert "tools.offline.render" in imports

    statspack = importlib.import_module("tools.offline.statspack")
    assert inspect.isclass(statspack.StatspackReport)
    assert issubclass(statspack.NotStatspackReport, Exception)
    assert list(inspect.signature(statspack.parse_statspack).parameters) == ["path"]
    assert set(TITLES) <= set(statspack.SECTIONS)
    report = statspack.parse_statspack(_fixture())
    assert isinstance(report, statspack.StatspackReport)
    assert isinstance(report.summary, dict) and isinstance(report.sections, dict)

    assert GENERATOR.is_file()
    assert FIXTURE.stat().st_size > 0
    assert "testhost" in FIXTURE.read_text(encoding="utf-8")
