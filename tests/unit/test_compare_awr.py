def test_contract_for_dependent_dba43():
    """Contract for DBA-43 (writes the skill text for compare-awr): the command
    `python -m tools compare-awr FIRST SECOND [--max-rows N] [--format md|json]`
    (module tools.commands.compare_awr), the fixtures awr_23ai_free_b.{html,txt},
    and `tests/support/make_awr_fixture.py --stem`. Shape only."""
    command = importlib.import_module("tools.commands.compare_awr")
    assert command.NAME == "compare-awr"
    for attr in ("HELP", "add_arguments", "run"):
        assert hasattr(command, attr), attr

    _require_command()
    help_out = _run_tools("compare-awr", "--help")
    assert help_out.returncode == 0, help_out.stderr
    for option in ("--max-rows", "--format", "FIRST", "SECOND"):
        assert option in help_out.stdout, option

    for path in FIXTURES_B.values():
        _fixture(path)
        assert "testhost" in path.read_text(encoding="utf-8"), f"{path.name}: host not replaced"
        assert parse_awr(path).summary["db_name"] == CONTAINER_DB_NAME

    # The generator must answer --help without a database: drop the password so the
    # current script (no options) exits 2 before connecting and never rewrites the
    # committed fixtures.
    env = {k: v for k, v in os.environ.items() if k != "ORACLE_TEST_PASSWORD"}
    gen = subprocess.run(
        [sys.executable, str(GENERATOR), "--help"],
        cwd=REPO_ROOT,
        env=env,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )
    assert gen.returncode == 0, gen.stderr
    assert "--stem" in gen.stdout

    # User decision 2026-11-13 (D-DBA-31): no licence check or edition guard.
    source = GENERATOR.read_text(encoding="utf-8").lower()
    for guard in ("control_management_pack_access", "dba_feature_usage", "edition"):
        assert guard not in source, f"generator checks {guard}"
