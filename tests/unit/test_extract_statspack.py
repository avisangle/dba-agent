import importlib
import inspect
import json
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURE_DIR = REPO_ROOT / "tests" / "fixtures" / "offline"
FIXTURE = FIXTURE_DIR / "statspack_23ai_free.txt"
OTHER_REPORTS = [FIXTURE_DIR / "awr_23ai_free.txt", FIXTURE_DIR / "ash_23ai_free.txt"]
GENERATOR = REPO_ROOT / "tests" / "support" / "make_statspack_fixture.py"
COMMAND_FILE = REPO_ROOT / "tools" / "commands" / "extract_statspack.py"
PENDING = REPO_ROOT / "pending.md"

CONTAINER_DB_NAME = "FREE"  # DB and instance name of the gvenzl/oracle-free CDB
TITLES = {
    "load_profile": "Load Profile",
    "instance_efficiency": "Instance Efficiency Indicators",
    "top_events": "Top 5 Timed Events",
    "sql_by_elapsed": "SQL ordered by Elapsed time",
    "sql_by_cpu": "SQL ordered by CPU",
    "sql_by_gets": "SQL ordered by Gets",
    "sql_by_reads": "SQL ordered by Reads",
    "init_params": "init.ora Parameters",
}
SQL_SECTIONS = [name for name in TITLES if name.startswith("sql_by_")]
SUMMARY_KEYS = [
    "db_name",
    "instance",
    "release",
    "begin_snap_id",
    "end_snap_id",
    "begin_time",
    "end_time",
    "elapsed",
    "db_time",
]
PAIR_COLUMNS = ["Statistic", "Value"]  # as extract-awr's instance_efficiency
SQL_TEXT_LIMIT = 200
DROPPED_LINE = re.compile(r"\b(\d+)\b.*\bdropped\b|\bdropped\b.*\b(\d+)\b", re.IGNORECASE)
NUMBER = re.compile(r"[\d,.]+")
PAIR = re.compile(r"(\S[^:]*?):\s+(\S+)")

# Summary values straight from the raw report.
RAW_PATTERNS = {
    "begin_snap": r"^\s*Begin Snap:\s+(\d+)\s+(\S+ \S+)",
    "end_snap": r"^\s*End Snap:\s+(\d+)\s+(\S+ \S+)",
    "elapsed": r"^\s*Elapsed:\s+([\d.,]+) \(mins\)",
    "db_time": r"^\s*DB time:\s+([\d.,]+) \(mins\)",
    # DB Id, Instance, Inst Num, Startup Time, Release, RAC (Database may be blank)
    "instance_line": r"(\d+) +(\S+) +\d+ +\d\d-\w{3}-\d\d \d\d:\d\d +(\S+) +(?:YES|NO) *$",
    "host": r"^Host Name.*\n~.*\n\s*(\S+)",
}

if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))


def _run_tools(*args):
    return subprocess.run(
        [sys.executable, "-m", "tools", *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )


def _fixture():
    assert FIXTURE.is_file(), f"fixture not found: {FIXTURE.relative_to(REPO_ROOT)}"
    return FIXTURE


def _lines(path=None):
    """Report lines with the page-break form feed removed; split("\\n"), not
    splitlines(), so a form feed does not add a line."""
    text = (path or _fixture()).read_text(encoding="utf-8")
    return [ln.replace("\f", "") for ln in text.split("\n")]


def _extract_json(path, *args):
    result = _run_tools("extract-statspack", str(path), "--format", "json", *args)
    assert result.returncode == 0, f"exit {result.returncode}: {result.stderr}"
    return json.loads(result.stdout)


def _raw(key):
    text = "\n".join(_lines())
    match = re.search(RAW_PATTERNS[key], text, re.MULTILINE)
    assert match, f"{key} not found in the raw fixture"
    return match.groups()


def _norm(text):
    return " ".join(text.split())


def _column(table, name):
    assert name in table["columns"], f"no column {name!r} in {table['columns']}"
    i = table["columns"].index(name)
    return [row[i] for row in table["rows"]]


def _is_title(line, title):
    return line == title or line.startswith(title + " ")


def _is_rule(line):
    """The indented dashes closing a section (column underlines start at column 0)."""
    return line.startswith(" ") and line.strip().startswith("-----") and set(line.strip()) == {"-"}


def _raw_blocks(title):
    """Data lines under each occurrence of `title` (one block per page): from the line
    after the column underline to the closing rule or the next page."""
    lines, blocks = _lines(), []
    starts = [i for i, ln in enumerate(lines) if _is_title(ln, title)]
    for s in starts:
        i = s + 1
        while i < len(lines) and not lines[i].startswith("---"):
            i += 1
        underline, i = lines[i], i + 1
        block = []
        while i < len(lines) and not _is_rule(lines[i]) and not any(
            _is_title(lines[i], t) for t in TITLES.values()
        ) and "DB/Inst:" not in lines[i]:
            block.append(lines[i])
            i += 1
        blocks.append((underline, block))
    assert blocks, f"title {title!r} not found in the raw fixture"
    return blocks


def _is_numbers_line(line):
    tokens = line.split()
    return len(tokens) >= 5 and all(NUMBER.fullmatch(t) for t in tokens)


def _md_tables(text):
    """Split Markdown output into pipe tables: (data_rows, next_nonblank_line) per table."""
    lines = text.splitlines()
    tables, i = [], 0
    while i < len(lines):
        if lines[i].lstrip().startswith("|"):
            start = i
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                i += 1
            rows = [ln for ln in lines[start:i] if not re.fullmatch(r"\s*\|[\s:|-]*\|\s*", ln)]
            following = next((ln for ln in lines[i:] if ln.strip()), "")
            tables.append((len(rows) - 1, following))  # minus the header row
        else:
            i += 1
    return tables


