import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURE_DIR = REPO_ROOT / "tests" / "fixtures" / "offline"
FIXTURES_A = {kind: FIXTURE_DIR / f"awr_23ai_free.{kind}" for kind in ("html", "txt")}
FIXTURES_B = {kind: FIXTURE_DIR / f"awr_23ai_free_b.{kind}" for kind in ("html", "txt")}
GENERATOR = REPO_ROOT / "tests" / "support" / "make_awr_fixture.py"

CONTAINER_DB_NAME = "FREE"
SUMMARY_KEYS = [
    "db_name",
    "instance",
    "release",
    "begin_snap_id",
    "end_snap_id",
    "begin_time",
    "end_time",
    "elapsed",
    "db_time",
]
SECTION_NAMES = ["load_profile", "top_events", "sql_by_elapsed"]
LOAD_PROFILE_COLUMNS = [
    "Statistic",
    "First per second",
    "Second per second",
    "Difference",
    "% change",
]
TOP_EVENTS_COLUMNS = [
    "Event",
    "First time (s)",
    "First % DB time",
    "Second time (s)",
    "Second % DB time",
]
SQL_COLUMNS = [
    "SQL Id",
    "First elapsed (s)",
    "First executions",
    "Second elapsed (s)",
    "Second executions",
    "SQL Text",
]
COLUMNS = {
    "load_profile": LOAD_PROFILE_COLUMNS,
    "top_events": TOP_EVENTS_COLUMNS,
    "sql_by_elapsed": SQL_COLUMNS,
}
SQL_TEXT_LIMIT = 200
ALL_ROWS = ("--max-rows", "100000")
DROPPED_LINE = re.compile(r"\b(\d+)\b.*\bdropped\b|\bdropped\b.*\b(\d+)\b", re.IGNORECASE)

if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tools.offline.awr import parse_awr  # noqa: E402  (exists since DBA-6)


def _run_tools(*args):
    return subprocess.run(
        [sys.executable, "-m", "tools", *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )


def _require_command():
    """Exit 2 is also argparse's answer to an unknown subcommand: make sure a passing
    exit-code assertion comes from compare-awr itself."""
    result = _run_tools("--help")
    assert "compare-awr" in result.stdout, "compare-awr is not a command of python -m tools"


def _fixture(path):
    assert path.is_file(), f"fixture not found: {path.relative_to(REPO_ROOT)}"
    return path


def _compare_json(first, second, *args):
    result = _run_tools("compare-awr", str(first), str(second), "--format", "json", *args)
    assert result.returncode == 0, f"exit {result.returncode}: {result.stderr}"
    return json.loads(result.stdout)


_SUFFIX = {"K": 1e3, "M": 1e6, "G": 1e9}


def _num(cell):
    """A report or computed figure as a float; None for a blank cell. AWR shortens
    large figures with K/M/G."""
    cell = cell.replace(",", "").strip()
    if not cell:
        return None
    scale = _SUFFIX.get(cell[-1].upper(), 1)
    return float(cell[:-1] if scale != 1 else cell) * scale


def _close(got, want, digits=0.06):
    """Computed cells may be rounded for display: allow the last printed digit."""
    return abs(got - want) <= digits + 0.001 * abs(want)


def _label(text):
    return text.strip().rstrip(":").strip()


def _source(path):
    """{section: {join key: {source column: cell}}} plus the summary, from parse_awr."""
    report = parse_awr(path)
    out = {}
    keys = {"load_profile": 0, "top_events": "Event", "sql_by_elapsed": "SQL Id"}
    for name, key_column in keys.items():
        table = report.sections[name]
        col = key_column if isinstance(key_column, int) else table.columns.index(key_column)
        rows = {}
        for row in table.rows:
            cells = dict(zip(table.columns, row, strict=False))
            key = _label(row[col]) if name == "load_profile" else row[col]
            rows[key] = cells
        out[name] = rows
    return report.summary, out


def _rows(section):
    return [dict(zip(section["columns"], row, strict=True)) for row in section["rows"]]


def _minutes(value):
    return float(value.split()[0].replace(",", ""))


def _check_sorted_desc(values, what):
    assert values == sorted(values, reverse=True), f"{what} not sorted largest first: {values}"


