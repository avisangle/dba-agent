# --- helpers -----------------------------------------------------------------


def _csv(header, rows) -> str:
    """`run-sql` CSV text as SQLcl prints it: quoted header, numbers bare, no
    footer under 6 rows, a blank line after the last record."""
    out = io.StringIO()
    writer = csv.writer(out, quoting=csv.QUOTE_NONNUMERIC, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return out.getvalue() + "\n"


def _result(header, rows, error=None) -> SqlResult:
    return SqlResult(_csv(header, rows), list(header), [[str(c) for c in r] for r in rows], "",
                     error)


def _script_result(script=SCRIPT, severity="INFO") -> SqlResult:
    return _result(["LINE_NO", "SCRIPT_LINE", "SEVERITY"],
                   [[n, line, severity] for n, line in script])


def _validate_script_result():
    return importlib.import_module("tools.checks.run").validate_script_result


def _fake_sqlcl(workdir: Path, run_sql_text: str) -> tuple[Path, Path]:
    """(executable standing in for `sql`, the log it writes once started). A
    missing log means no SQLcl process was started."""
    workdir.mkdir(parents=True, exist_ok=True)
    log = workdir / "fake-sqlcl.log"
    script = workdir / "fake-sqlcl.json"
    script.write_text(json.dumps({
        "log": str(log),
        "tools": ["list-connections", "connect", "run-sql", "run-sqlcl", "disconnect"],
        "calls": {
            "list-connections": {"text": CONNECTION},
            "connect": {"text": "Connected."},
            "run-sql": {"text": run_sql_text},
            "run-sqlcl": {"text": "refused"},
            "disconnect": {"text": "Disconnected."},
        },
    }))
    return fake_sql_bin(workdir, script), log


def _log(log: Path) -> tuple[list[str], list[dict]]:
    """(argv the fake `sql` was started with, tools/call params in order)."""
    lines = [json.loads(ln) for ln in log.read_text().splitlines() if ln.strip()]
    calls = [m["params"] for m in lines[1:] if m.get("method") == "tools/call"]
    return lines[0]["argv"], calls


def _advise(tmp_path: Path, *args, sqlcl):
    env = {**os.environ, f"{PACK_NAME.upper()}_HOME": str(tmp_path / "pack-home"),
           "SQLCL_BIN": str(sqlcl)}
    return subprocess.run(
        [sys.executable, "-m", "tools", "advise", *args],
        cwd=REPO_ROOT, env=env, capture_output=True, text=True, timeout=120, check=False,
    )


def _command_exists(proc):
    assert "invalid choice" not in proc.stderr, proc.stderr
    assert "unrecognized arguments" not in proc.stderr, proc.stderr


def _files(root: Path) -> list[Path]:
    return sorted(p for p in root.rglob("*") if p.is_file()) if root.exists() else []


def _written(tmp_path: Path) -> list[Path]:
    """Files under the pack home's scripts folder."""
    return _files(tmp_path / "pack-home" / "scripts")


def _split(path: Path, n_body: int) -> tuple[list[str], list[str]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    return lines[:-n_body] if n_body else lines, lines[-n_body:] if n_body else []


class FakeSession:
    """Stands in for a SqlclSession in the harness: records SQL, returns `result`."""

    def __init__(self, result: SqlResult):
        self.result = result
        self.sent: list[str] = []

    def run_sql(self, sql: str) -> SqlResult:
        self.sent.append(sql)
        return self.result


class FakeRequest:
    """Stands in for pytest's `request` in the harness's test_check."""

    def __init__(self, **values):
        self.values = {"db_version": (23, 26, 3, 0, 0), **values}

    def getfixturevalue(self, name):
        assert name in self.values, f"harness asked for an unexpected fixture {name!r}"
        return self.values[name]


